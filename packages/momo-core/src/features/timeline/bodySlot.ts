// =============================================================================
// 본문 칸을 만들 것인가 (이슈 #1465 → #1478).
//
// 이 자리는 두 가지를 묻는다. 첫 물음은 **자격**이다 — 이 행의 카드가 이미 자기
// 제목과 행으로 본문을 말해 버렸는가(`cardKeepsBody` · `rowPresentation.keepsBody`).
// 승인 카드와 도구 카드는 그렇고, 요약 없는 완료 리포트는 아니다("본문이 곧 빠진
// 요약이다", `agentCardModel`).
//
// 두 번째 물음이 이 파일이다 — **살릴 본문이 실제로 있는가.** 둘이 갈라지는 자리가
// 요약 없는 완료 리포트다: 자격은 true 인데 살릴 본문이 없다.
//
// ## 왜 코어인가 (이슈 #1478)
//
// 이 판정은 #1465 에서 **웹에만** 섰다. 폰은 같은 자리에서 `body !== ''` 로 물었고,
// 그것은 한 칸 좁다 — 공백만 있는 본문(`"   \n  "`)은 `!== ''` 를 통과해 본문 칸을
// 얻고, 그 공백이 그대로 그려져 카드 위에 빈 줄이 선다. 웹이 #1465 로 고친 바로 그
// 결함이 폰에 그대로 남아 있었다(역방향 패리티 잔차).
//
// 두 표면이 각자 적은 규칙은 한 번만 고쳐지고 나머지 한 번은 잊힌다 — `pinExcerpt`
// 와 `appVoice` 를 코어로 올린 것과 같은 이유다(#1146 N2 · #1149 M4). 판정은 여기
// 하나 있고, 웹과 폰은 그 하나를 소비한다.
//
// ## 왜 `rowModel.ts` 가 아니라 별도 파일인가
//
// `keepsBody` 옆에 두면 한 화면 안에 두 물음이 붙고, 붙은 둘은 언젠가 하나로
// 접힌다 — 그 접힘이 정확히 #1465 가 기록한 혼동이다(자격을 내용으로 읽는 것).
// 물음이 둘이면 파일도 둘이다. `rowModel` 은 `Message` 를 받아 **어느 칸이 이 행을
// 갖는지**를 정하고, 이 파일은 문자열 하나를 받아 **그 문자열에 사람이 읽을 글자가
// 있는지**만 답한다. 후자는 `Message` 조차 필요 없다는 것이 그 차이의 증거다.
//
// ## 실측 (웹, 게이트만 실린 리포트, 1280×900)
//
// `clients/web/scripts/capture-completion.mjs` 가 잰 값이다.
//
// | body            | `<p>` | 높이 |
// |-----------------|-------|------|
// | 키 자체가 없음   | 있음  | 0px  |
// | `""`            | 있음  | 0px  |
// | `"   \n  "`     | 있음  | 46px |
//
// 부재와 빈 문자열에서 그 문단은 **자리를 차지하지 않는다**. 빈 블록에는 줄상자가
// 생기지 않기 때문이고, 그래서 #1454 가 커밋하는 모양(본문 키 부재)에서 눈에 보이는
// 어긋남은 없었다 — 남는 것은 행 안의 문단 노드 하나다. 눈이 보는 결함은 **공백만
// 있는 본문**에 있다: `whitespace-pre-wrap` 이 그 공백을 그대로 그려 카드 위에 빈
// 줄 두 개(46px)가 선다. 폰은 CSS 가 아니라 `<Text>` 지만 결론은 같다 — 줄바꿈이
// 든 문자열은 줄을 만든다.
//
// 그래서 판정은 `trim()` 으로 한다. `!== ''` 보다 한 칸 넓고, 넓은 쪽이 옳다:
// 사람이 읽을 글자가 없다는 사실은 공백의 개수와 무관하다.
//
// 묘비와 편집기는 이 판정을 거치지 않는다 — 두 클라의 `MessageRow` 가 그 둘을 이
// 갈래 **앞에** 둔다. 둘 다 본문 자리에 서지만 본문이 아니다: 묘비는 지워진 본문에
// **대한** 앱의 서술이고, 편집기는 빈 본문에서 특히 필요한 입력 상자다.
// =============================================================================

/**
 * 사람이 읽을 글자가 이 본문에 있는가.
 *
 * `null` 도 받는다. 타입은 `body?: string` 이지만 실시간 프레임은 `"body": null` 을
 * 싣고(`momo_messaging::build_broadcast_payload`), 그 `null` 을 부재로 바꾸는 것은
 * 코어의 `payloadToMessage` 다. 그 정규화 하나에 화면 판정을 기대지 않는다.
 */
export function hasRenderableBody(body: string | null | undefined): boolean {
  return (body ?? "").trim() !== "";
}
