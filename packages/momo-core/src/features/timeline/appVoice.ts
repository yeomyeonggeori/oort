// =============================================================================
// 앱이 말하는 문장 — 두 표면이 함께 쓰는 표시 (이슈 #1149 M4).
//
// 대화 안의 글자는 거의 전부 **누군가 친 것**이다. 그런데 몇 줄은 아니다 —
// 「삭제된 메시지」, 「내용 없는 메시지」. 이것들은 메시지가 아니라 **메시지에
// 대한 서술**이고, 사람이 그 둘을 헷갈리면 앱의 해명을 남의 말로 읽는다.
//
// ## 왜 코어인가
//
// 폰이 먼저 이 축을 세웠고(`clients/mobile/src/features/conversation/appVoice.ts`
// — 왜 italic 이 아니라 `※` 인지, 왜 색으로는 못 푸는지, 왜 낭독 라벨에는 붙이지
// 않는지가 거기 길게 적혀 있다), 웹은 같은 사실을 아무 표시 없이 그리고 있었다.
// 고정 목록의 빈 본문이 그 자리였다: 코어가 `PinExcerpt.empty` 로 「이 글자는
// 저자의 것이 아니다」를 이미 쥐여 주는데도 웹은 그 깃발을 읽지 않아서, 같은
// 카드가 폰에서는 「※ 내용 없는 메시지」로 서고 웹에서는 **저자가 그렇게 쓴 것**
// 처럼 섰다.
//
// 그래서 표시를 짓는 자리를 하나로 둔다. `pinExcerpt` 를 코어로 올린 것과 같은
// 이유다(#1146 N2): 두 표면이 각자 적은 규칙은 한 번만 고쳐지고, 나머지 한 번은
// 잊힌다. 폰의 파일은 이 두 값을 다시 내보내는 쪽이 됐을 뿐 동작이 그대로다.
//
// ## 웹에서도 `※` 인 이유 (italic 은 여기서도 무동작이다)
//
// 폰이 italic 을 버린 이유는 RN 이 아니라 **문자체계**였다 — 한글 시스템 서체에
// italic 페이스가 없다. 웹도 같다: `MessageBody.tsx` 는 마크다운의 `em` 조차
// `em-latin-only` 로 내려 한글에 기울기를 합성하지 않는다(`tokens.css`). 즉 웹에서
// italic 을 쓰면 라틴에만 걸리는 축이 되고, 우리가 출하하는 문장은 대부분 한글이다.
// 남는 것은 색 한 단계인데, 그것은 이미 「덜 중요함」이 쓰고 있다.
//
// 표시는 하나다. 어느 종류의 서술인지는 이미 낱말이 말한다.
// =============================================================================

/** 앱이 말하는 문장 앞에 서는 주(註) 기호. */
export const APP_NOTE_MARK = "※";

/**
 * 앱의 서술 한 줄을 짓는다.
 *
 * 자리마다 `` `${APP_NOTE_MARK} ${text}` `` 를 손으로 쓰면 사이 공백이 한 곳에서
 * 어긋나고, 그러면 같은 낱말이 화면에서 두 모양으로 나온다. 짓는 자리를 하나로
 * 둔다.
 */
export function appNote(text: string): string {
  return `${APP_NOTE_MARK} ${text}`;
}
