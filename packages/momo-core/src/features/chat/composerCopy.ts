// ## 어느 문장을 골랐나 — **폰 쪽**, 그리고 그 이유
//
// 이 제품의 오프라인 문장에는 이미 모양이 있다: **지금 무엇이 안 되는가 → 다시
// 연결되면 여기서 무엇을 할 수 있는가.** `APPROVAL_OFFLINE_COPY`("…다시 연결되면
// 여기서 승인하거나 거부할 수 있습니다")도, 작업 인수 문장(`workstreams/
