// 키보드 힌트의 표기법 — 한 벌 (#1384 CRUN-3).
//
// ## 무엇이 갈라져 있었나 (실측, 웹)
//
//   sidebar/Sidebar.tsx:401      "⌘K"                                  text-meta
//   chat/Composer.tsx:894        "Enter로 보내기, Shift+Enter로 줄바꿈"   text-meta
//   timeline/MessageEditor.tsx:117 "Enter 저장 · Shift+Enter 줄바꿈 · Esc 취소"  text-timestamp
//
// 같은 종류의 정보가 **두 크기**(12px·11px)로 서고, **두 이음쇠**(쉼표·가운뎃점)를
// 쓰고, **두 문법**(「Enter로 보내기」·「Enter 저장」)으로 적혀 있었다. 셋 다 한
// 클라 안의 내부 불일치(디자인 시스템 §5.3, 10위)이고 기계가 안 잡는 축이다.
//
// ## 고른 표기: 산문. 테두리 친 kbd 칩이 아니다.
//
// 칩을 안 쓰는 이유는 취향이 아니라 §3 위계다: 이 시스템에서 **테두리는 컨트롤의
// 어포던스를 진다**(`--line-strong`, §3.3 의 프리미티브 분류). 누를 수 없는 글자에
// 테두리를 두르면 화면에서 가장 작은 것이 컨트롤의 옷을 입는다. 게다가 11~12px
// 글자를 칩으로 만들려면 닫힌 간격 격자(4·8·12…) 밖의 안쪽 여백이 필요해서
// 임의값이 들어오고, 그것은 프리플라이트 `arbitrary_tw` 가 막는 자리다.
//
// 그래서 표기는 넷으로 고정한다:
//
//   1. 역할  `text-meta` + `text-ink-muted` — 12px 하나. 11px(`text-timestamp`)은
//            묘비의 크기이지 안내의 크기가 아니다.
//   2. 이음쇠 `HINT_SEPARATOR` (` · `) 하나. 쉼표는 문장 안에서만 쓴다.
//   3. 문법  `<키>로 <동사>`. 키가 먼저 오는 이유는 눈이 찾는 것이 키라서다.
//   4. 폭    `wide-only`. 폰에는 ⌘도 Shift+Enter 도 없다(goal B6·B8 H4).
//
// 키 이름은 **키에 새겨진 대로** 적는다: `Enter` · `Shift+Enter` · `Esc` · `⌘K`.
// 조합 수식키는 기호로 붙여 쓰고(`⌘K`·`⌘⇧K`·`⌘,`) 이름 있는 키에 수식키가 붙으면
// `+` 로 잇는다(`Shift+Enter`) — 새 규칙이 아니라 이미 그렇게 적혀 있던 것에
// 이름을 붙인 것이고, 새 단축키는 이 티켓이 만들지 않는다.
//
// ## 이 표기가 **덮지 않는** 두 번째 어법 — 괄호 키 (툴팁 register)
//
// 위 규칙은 **화면에 상시로 서 있는 힌트 줄**의 것이다. 이 앱에는 그것과 나란히
// 사는 다른 어법이 하나 더 있고, 그것은 잘못 통일된 것이 아니라 **다른 자리**다:
//
//   sidebar/Sidebar.tsx:578   title="새 다이렉트 메시지 (⌘⇧K)"
//   sidebar/Sidebar.tsx:690   title="설정 (⌘,)"
//   chat/Composer.tsx:838     title="메시지 보내기 (Enter)"
//
// 어법은 `<동작> (<키>)` — 힌트 줄과 **정반대 순서**이고, 그것이 맞다:
//
//   * 이것들은 `title`/툴팁이라 **컨트롤의 이름 뒤에 붙는 꼬리표**다. 이름이 먼저
//     오지 않으면 툴팁이 무엇에 대한 것인지가 뒤로 밀린다.
//   * 힌트 줄은 반대로 **키를 찾는 눈**이 읽는 줄이라 키가 앞에 선다.
//   * 툴팁은 포인터가 있어야 열리므로 폰에서 존재하지 않는다. `wide-only` 같은
//     접힘 규칙이 필요 없는 것도 그래서다.
//
// 그러니 다음에 통일하러 오는 사람에게: **이 셋을 힌트 줄 문법으로 바꾸지 마라.**
// 두 어법은 두 자리이고, 자리가 둘이면 어법도 둘인 것이 일관성이다. 반대로 새
// 툴팁을 지을 때는 셋과 같은 `<동작> (<키>)` 로 짓고, 새 힌트 줄은 위 넷으로 짓는다.
//
// 아래 두 줄이 값을 들고 `composerCopy.test.ts` 가 위 넷 중 문장에 해당하는
// 것(이음쇠·문법·대시 없음)을 **전수로** 잰다. 재지 않는 규약은 규약이 아니다.
// 툴팁 어법은 여기서 값을 들지 않는다 — 그 문장들은 컨트롤의 이름이라 컨트롤
// 옆에 살고, 이 파일이 그것까지 들면 버튼의 이름이 컴포저 카피 파일로 이사한다.
