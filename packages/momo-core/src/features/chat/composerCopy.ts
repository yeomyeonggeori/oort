// 말하고, 언제 다시 보낼 수 있는지도, 그 일이 **이 상자에서** 일어난다는 것도
// 말하지 않는다 — 읽는 사람은 기다리라는 말은 들었는데 어디서 기다릴지는 못
// 들었다. 승인 카드는 같은 상황에서 그것을 말해 주는데 컴포저만 안 말한다.
//
// 폰 문장은 셋을 다 말하고(지금 못 보낸다 · 쓰던 글은 그대로다 · 다시 연결되면
