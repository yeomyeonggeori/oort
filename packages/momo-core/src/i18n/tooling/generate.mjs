// Build-only ICU compiler. Never import this module from a product entry point.
import {readFileSync, readdirSync, mkdirSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {parse, TYPE} from '@formatjs/icu-messageformat-parser';
import ts from 'typescript';

const HERE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LOCALES = ['en-US', 'ko-KR'];
const KEY = /^[a-z][a-zA-Z0-9]*\.[a-z][a-zA-Z0-9]*\.[a-z][a-zA-Z0-9]*$/;
const ARG = /^[a-z][a-zA-Z0-9]*$/;
const HEADER = '// Generated by i18n/tooling/generate.mjs. Do not edit.\n';

function readCatalog(file) {
  const source = readFileSync(file, 'utf8');
  const value = JSON.parse(source);
  if (!value || Array.isArray(value) || typeof value !== 'object') {
    throw new Error(`${file}: expected a JSON object`);
  }
  // JSON.parse silently keeps the last duplicate. Inspect tokens before accepting it.
  const sf = ts.createSourceFile(file, source, ts.ScriptTarget.ES2022, true, ts.ScriptKind.JSON);
  function visit(node) {
    if (ts.isObjectLiteralExpression(node)) {
      const seen = new Set();
      for (const property of node.properties) {
        const name = property.name?.text;
        if (seen.has(name)) throw new Error(`${file}: duplicate key ${name}`);
        seen.add(name);
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(sf);
  return value;
}

function argumentsOf(ast, key) {
  const args = Object.create(null);
  function visit(elements) {
    for (const node of elements) {
      if (node.type === TYPE.literal || node.type === TYPE.pound) continue;
      if (node.type === TYPE.tag) throw new Error(`${key}: rich text needs an approved token adapter`);
      if (!ARG.test(node.value)) throw new Error(`${key}: invalid argument name`);
      const kind = node.type === TYPE.argument ? 'value'
        : node.type === TYPE.select ? 'string'
          : node.type === TYPE.date || node.type === TYPE.time ? 'date' : 'number';
      args[node.value] = mergeKind(args[node.value], kind, key);
      if (node.type === TYPE.plural || node.type === TYPE.select) {
        if (!Object.hasOwn(node.options, 'other')) throw new Error(`${key}: missing other`);
        for (const option of Object.values(node.options)) visit(option.value);
      }
    }
  }
  visit(ast);
  return Object.fromEntries(Object.entries(args).sort(([a], [b]) => a.localeCompare(b, 'en')));
}

function mergeKind(a, b, key) {
  if (!a || a === 'value') return b;
  if (b === 'value' || a === b) return a;
  throw new Error(`${key}: conflicting argument types ${a}/${b}`);
}

/** P0-5 may validate an isolated catalog fixture with the same compiler as production. */
export function compileCatalogs(root = join(HERE, 'catalogs')) {
  const catalogs = {};
  const schemas = {};
  for (const locale of LOCALES) {
    const catalog = {};
    const schema = {};
    for (const feature of readdirSync(join(root, locale)).filter(f => f.endsWith('.json')).sort()) {
      const input = readCatalog(join(root, locale, feature));
      for (const [key, source] of Object.entries(input)) {
        if (!KEY.test(key) || !key.startsWith(`${feature.slice(0, -5)}.`)) {
          throw new Error(`${locale}: invalid feature.surface.intent key ${key}`);
        }
        if (Object.hasOwn(catalog, key)) throw new Error(`${locale}: duplicate key ${key}`);
        if (typeof source !== 'string' || !source.trim()) throw new Error(`${key}: empty message`);
        const ast = parse(source, {captureLocation: false, requiresOtherClause: true});
        if (ast.every(n => n.type === TYPE.literal && !n.value.trim())) throw new Error(`${key}: blank message`);
        catalog[key] = ast;
        schema[key] = argumentsOf(ast, key);
      }
    }
    if (!Object.keys(catalog).length) throw new Error(`${locale}: empty catalog`);
    catalogs[locale] = Object.fromEntries(Object.entries(catalog).sort(([a], [b]) => a.localeCompare(b, 'en')));
    schemas[locale] = schema;
  }
  const keys = Object.keys(catalogs['en-US']);
  for (const locale of LOCALES) {
    if (JSON.stringify(Object.keys(catalogs[locale])) !== JSON.stringify(keys)) {
      throw new Error(`${locale}: key set differs from en-US`);
    }
  }
  const args = {};
  for (const key of keys) {
    const english = schemas['en-US'][key];
    const korean = schemas['ko-KR'][key];
    if (JSON.stringify(Object.keys(english)) !== JSON.stringify(Object.keys(korean))) {
      throw new Error(`${key}: argument names differ`);
    }
    args[key] = Object.fromEntries(Object.keys(english).map(name => {
      const kind = mergeKind(english[name], korean[name], key);
      return [name, kind === 'value' ? 'string' : kind];
    }));
  }
  return {catalogs, args};
}

/** P0-5 CI uses --check; P0-6 can read the generated key/spec exports. */
export function generate({catalogRoot = join(HERE, 'catalogs'), outputRoot = join(HERE, 'generated'), check = false} = {}) {
  const {catalogs, args} = compileCatalogs(catalogRoot);
  const outputs = {};
  for (const locale of LOCALES) {
    outputs[`${locale}.ts`] = HEADER + 'import type { MessageCatalog } from "../types";\n\n'
      + `export const catalog: MessageCatalog = ${JSON.stringify(catalogs[locale], null, 2)};\n`;
  }
  const typeFor = kind => kind === 'date' ? 'number | Date' : kind;
  outputs['messages.ts'] = HEADER
    + `export const messageKeys = ${JSON.stringify(Object.keys(args), null, 2)} as const;\n\n`
    + 'export type MessageKey = typeof messageKeys[number];\n\n'
    + `export const argumentSpecs = ${JSON.stringify(args, null, 2)} as const;\n\n`
    + 'export interface MessageArgs {\n'
    + Object.entries(args).map(([key, fields]) => `  ${JSON.stringify(key)}: ${Object.keys(fields).length
      ? '{ ' + Object.entries(fields).map(([name, kind]) => `${name}: ${typeFor(kind)}`).join('; ') + ' }'
      : 'Record<string, never>'};`).join('\n')
    + '\n}\n';
  if (!check) mkdirSync(outputRoot, {recursive: true});
  for (const [file, content] of Object.entries(outputs)) {
    const path = join(outputRoot, file);
    if (check) {
      if (readFileSync(path, 'utf8') !== content) throw new Error(`Stale generated i18n file: ${file}`);
    } else writeFileSync(path, content);
  }
  return outputs;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generate({check: process.argv.includes('--check')});
}
