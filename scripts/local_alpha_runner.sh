print_plan() {
  echo "[local-alpha] mode: plan"
  echo "[local-alpha] repo: $REPO_ROOT"
  echo "[local-alpha] AWS resources: none"
  echo "[local-alpha] hermes mode: $HERMES_MODE"
  echo "[local-alpha] external runtime smoke: $EXTERNAL_SMOKE"
  if [ "$SECRET_ENV_FILE" != "" ]; then
    echo "[local-alpha] secret env: $SECRET_ENV_FILE (outside repo enforced)"
  elif [ "$HERMES_MODE" = "external" ]; then
    echo "[local-alpha] secret env: required for external Hermes"
  else
    echo "[local-alpha] secret env: generated dev-only env outside repo during execute"
  fi
  echo "[local-alpha] evidence root: $EVIDENCE_ROOT"
  echo
  if [ "$HERMES_MODE" = "external" ] && [ "$EXTERNAL_SMOKE" = "1" ]; then
    echo "Execute will delegate to scripts/verify_external_agent_provider.sh:"
    echo "  1. use .env.worktree/.env/infra/.env.example as the local stack base env"
    echo "  2. load --secret-env as EXTERNAL_AGENT_PROVIDER_ENV_FILE"
    echo "  3. require credentialed external runtime config"
    echo "  4. run provider SSE preflight"
    echo "  5. boot local MomoServer/OutboxRelay/AgentWorker and send one @agent roundtrip"
    echo "  6. write redacted external-agent-provider evidence"
    return 0
  fi
  echo "Execute will run:"
  echo "  1. docker compose up -d --wait (PG18 + Centrifugo v6, local subscribe proxy override)"
  echo "  2. scripts/migrate.sh"
  echo "  3. scripts/verify_rls.sh to prepare momo_app/momo_relay/momo_worker roles"
  echo "  4. MomoServer on http://127.0.0.1:\${PORT:-8080}"
  echo "  5. OutboxRelay and AgentWorker from SwiftPM"
  if [ "$HERMES_MODE" = "external" ] && [ "$EXTERNAL_SMOKE" = "1" ]; then
    echo "  6. delegate to scripts/verify_external_agent_provider.sh for provider SSE + momo @agent roundtrip"
  else
    echo "  6. mock Hermes locally or verify external Hermes env"
  fi
  echo "  7. swift run --package-path clients/macOS MomoMacSmoke"
  echo "  8. evidence summary with URLs, redacted env, logs, and stop command"
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    plan|--plan|--dry-run|dry-run)
      MODE=plan
      shift
      ;;
    execute|--execute)
      MODE=execute
      shift
      ;;
    --hermes)
      [ "$#" -ge 2 ] || fail "--hermes requires mock or external"
      HERMES_MODE=$2
      case "$HERMES_MODE" in mock|external) ;; *) fail "--hermes must be mock or external" ;; esac
      shift 2
      ;;
    --secret-env)
      [ "$#" -ge 2 ] || fail "--secret-env requires an absolute path"
      SECRET_ENV_FILE=$(abs_existing_file "$2")
      assert_secret_env_outside_repo "$SECRET_ENV_FILE"
      shift 2
      ;;
    --external-smoke)
      EXTERNAL_SMOKE=1
      shift
      ;;
    --evidence-root)
      [ "$#" -ge 2 ] || fail "--evidence-root requires a path"
      EVIDENCE_ROOT=$(abs_dir_path "$2")
      shift 2
      ;;
    --stop-after-smoke)
      KEEP_RUNNING=0
      shift
      ;;
    --api-proxy-host)
      [ "$#" -ge 2 ] || fail "--api-proxy-host requires a host"
      API_PROXY_HOST=$2
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      fail "unknown argument: $1"
      ;;
  esac
done

[ "$EXTERNAL_SMOKE" = "0" ] || [ "$HERMES_MODE" = "external" ] || \
  fail "--external-smoke requires --hermes external"

case "$MODE" in
  plan)
    print_plan
    exit 0
    ;;
  execute) ;;
  *) fail "invalid mode: $MODE" ;;
esac

[ "$HERMES_MODE" = "mock" ] || [ "$SECRET_ENV_FILE" != "" ] || \
  fail "--hermes external requires --secret-env /path/outside/repo.env"

external_smoke_base_env() {
  if [ "${LOCAL_ALPHA_BASE_ENV_FILE:-}" != "" ]; then
    abs_existing_file "$LOCAL_ALPHA_BASE_ENV_FILE"
    return
  fi
  for candidate in "$REPO_ROOT/.env.worktree" "$REPO_ROOT/.env" "$REPO_ROOT/infra/.env.example"; do
    if [ -f "$candidate" ]; then
      printf '%s\n' "$candidate"
      return
    fi
  done
  fail "no base env file found for external smoke"
}

if [ "$EXTERNAL_SMOKE" = "1" ]; then
  BASE_ENV_FILE=$(external_smoke_base_env)
  echo "[local-alpha] delegating external runtime smoke"
  echo "[local-alpha] base env: $BASE_ENV_FILE"
  echo "[local-alpha] provider secret env: $SECRET_ENV_FILE"
  ENV_FILE="$BASE_ENV_FILE" \
  EXTERNAL_AGENT_PROVIDER_ENV_FILE="$SECRET_ENV_FILE" \
  EXTERNAL_AGENT_PROVIDER_REQUIRE_CREDENTIALS=1 \
    "$REPO_ROOT/scripts/verify_external_agent_provider.sh"
  exit $?
fi

RUN_ID=$(date -u '+%Y%m%dT%H%M%SZ')
EVIDENCE_DIR=$EVIDENCE_ROOT/$RUN_ID
LOG_DIR=$EVIDENCE_DIR/logs
PIDS_FILE=$EVIDENCE_DIR/pids.env
mkdir -p "$LOG_DIR"
: >"$PIDS_FILE"

if [ "$SECRET_ENV_FILE" != "" ]; then
  ENV_FILE=$SECRET_ENV_FILE
else
  write_generated_env
fi

load_env_file
write_local_centrifugo_config
write_stop_script

require_cmd docker
require_cmd curl
require_cmd swift
require_cmd python3

if [ "$HERMES_MODE" = "external" ]; then
  [ "$HERMES_BASE_URL" != "" ] || fail "HERMES_BASE_URL is required in --secret-env"
  [ "$HERMES_API_KEY" != "" ] || fail "HERMES_API_KEY is required in --secret-env"
  case "$HERMES_API_KEY" in
    change-me*|dev-insecure*) fail "HERMES_API_KEY looks like a placeholder" ;;
  esac
fi

echo "[local-alpha] evidence: $EVIDENCE_DIR"
echo "[local-alpha] env file: $ENV_FILE"
echo "[local-alpha] AWS resources: none"

# MOMO-316: --wait가 postgres/centrifugo healthcheck healthy까지 대기하므로
# 별도 wait_compose_healthy 폴링이 필요 없다. wait_http는 compose 밖의
# host 프로세스(mock Hermes/MomoServer)에만 남는다 — 이들은 compose 서비스가
# 아니라 healthcheck를 붙일 수 없다.
run_cmd docker-up docker compose --env-file "$ENV_FILE" \
  -f "$REPO_ROOT/infra/docker-compose.yml" \
  -f "$COMPOSE_OVERRIDE" up -d --wait
run_cmd docker-ps docker compose --env-file "$ENV_FILE" \
  -f "$REPO_ROOT/infra/docker-compose.yml" \
  -f "$COMPOSE_OVERRIDE" ps

run_cmd migrate sh "$REPO_ROOT/scripts/migrate.sh"
run_cmd verify-rls sh "$REPO_ROOT/scripts/verify_rls.sh"

if [ "$HERMES_MODE" = "mock" ]; then
  MOCK_PID=$(start_bg mock-hermes python3 "$REPO_ROOT/scripts/mock_hermes.py" \
    --host 127.0.0.1 --port "$HERMES_PORT")
  wait_http "http://127.0.0.1:${HERMES_PORT}/health" "mock Hermes"
else
  echo "[local-alpha] external Hermes env present: $(redact_url "$HERMES_BASE_URL")"
fi

APP_DATABASE_URL=${APP_DATABASE_URL:-postgres://momo_app:momo_app_dev_pw@localhost:${POSTGRES_PORT}/${POSTGRES_DB}}
RELAY_DATABASE_URL=${RELAY_DATABASE_URL:-postgres://momo_relay:momo_relay_dev_pw@localhost:${POSTGRES_PORT}/${POSTGRES_DB}}
WORKER_DATABASE_URL=${WORKER_DATABASE_URL:-postgres://momo_worker:momo_worker_dev_pw@localhost:${POSTGRES_PORT}/${POSTGRES_DB}}

SERVER_PID=$(start_bg server env \
  DATABASE_URL="$APP_DATABASE_URL" \
  CENT_API_URL="$CENT_API_URL" \
  CENT_API_KEY="$CENT_API_KEY" \
  CENT_TOKEN_HMAC="$CENT_TOKEN_HMAC" \
  JWT_HMAC="$JWT_HMAC" \
  PORT="$PORT" \
  HOST="$HOST" \
  swift run --package-path server MomoServer)
wait_http "http://127.0.0.1:${PORT}/health" "MomoServer"

RELAY_PID=$(start_bg relay env \
  RELAY_DATABASE_URL="$RELAY_DATABASE_URL" \
  DATABASE_URL="$RELAY_DATABASE_URL" \
  CENT_API_URL="$CENT_API_URL" \
  CENT_API_KEY="$CENT_API_KEY" \
  RELAY_POLL_INTERVAL_MS="${RELAY_POLL_INTERVAL_MS:-100}" \
  swift run --package-path relay/OutboxRelay OutboxRelay)

WORKER_PID=$(start_bg worker env \
  RELAY_DATABASE_URL="$WORKER_DATABASE_URL" \
  DATABASE_URL="$WORKER_DATABASE_URL" \
  CENT_API_URL="$CENT_API_URL" \
  CENT_API_KEY="$CENT_API_KEY" \
