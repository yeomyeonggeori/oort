compose_cmd() {
  docker compose --env-file "$ENV_FILE" \
    -f "$REPO_ROOT/infra/docker-compose.yml" \
    -f "$COMPOSE_OVERRIDE" "$@"
}

log_command_line() {
  printf '$'
  for arg in "$@"; do
    printf ' %s' "$(redact_command_arg "$arg")"
  done
  printf '\n'
}

redact_command_arg() {
  arg=$1
  case "$arg" in
    *=*)
      key=${arg%%=*}
      value=${arg#*=}
      upper_key=$(printf '%s' "$key" | tr '[:lower:]' '[:upper:]')
      case "$upper_key" in
        *PASSWORD*|*SECRET*|*TOKEN*|*KEY*|*HMAC*|*DATABASE_URL*)
          if [ "$value" = "" ]; then
            printf '%s=' "$key"
          else
            printf '%s=<set:redacted>' "$key"
          fi
          return
          ;;
        *URL*)
          printf '%s=%s' "$key" "$(redact_url "$value")"
          return
          ;;
      esac
      ;;
  esac

  case "$arg" in
    *://*@*) redact_url "$arg" ;;
    *) printf '%s' "$arg" ;;
  esac
}

run_cmd() {
  name=$1
  shift
  log="$LOG_DIR/${name}.log"
  echo "[local-alpha] ==> $name"
  {
    log_command_line "$@"
    (cd "$REPO_ROOT" && "$@")
  } >"$log" 2>&1 || {
    echo "[local-alpha] failed: $name (log: $log)" >&2
    tail -80 "$log" >&2 || true
    exit 1
  }
}

start_bg() {
  name=$1
  shift
  log="$LOG_DIR/${name}.log"
  echo "[local-alpha] ==> start $name (log: $log)" >&2
  log_command_line "$@" >"$log" 2>&1
  nohup sh -c 'repo=$1; shift; cd "$repo" || exit 1; exec "$@"' sh "$REPO_ROOT" "$@" >>"$log" 2>&1 </dev/null &
  pid=$!
  echo "$name=$pid" >>"$PIDS_FILE"
  printf '%s\n' "$pid"
}

wait_http() {
  url=$1
  name=$2
  deadline=$(($(date +%s) + 90))
  while [ "$(date +%s)" -lt "$deadline" ]; do
    if curl -fsS "$url" >/dev/null 2>&1; then
      echo "[local-alpha] ready: $name $url"
      return 0
    fi
    sleep 1
  done
  fail "$name did not become ready: $url"
}

# (MOMO-316) wait_compose_healthy 폴링 헬퍼는 제거됨 —
# compose 서비스 대기는 `docker compose up -d --wait`(healthcheck 기반)가 담당한다.

assert_pid_alive() {
  pid=$1
  name=$2
  log=$3
  if ! kill -0 "$pid" 2>/dev/null; then
    echo "[local-alpha] $name exited early (log: $log)" >&2
    tail -80 "$log" >&2 || true
    exit 1
  fi
}

write_stop_script() {
  STOP_SCRIPT="$EVIDENCE_DIR/stop-local-alpha.sh"
  cat >"$STOP_SCRIPT" <<EOF
#!/usr/bin/env sh
set -eu
REPO_ROOT='$REPO_ROOT'
ENV_FILE='$ENV_FILE'
COMPOSE_OVERRIDE='$COMPOSE_OVERRIDE'
PIDS_FILE='$PIDS_FILE'

if [ -f "\$PIDS_FILE" ]; then
  awk -F= '{print \$2}' "\$PIDS_FILE" | while IFS= read -r pid; do
    if [ "\$pid" != "" ] && kill -0 "\$pid" 2>/dev/null; then
      kill "\$pid" 2>/dev/null || true
    fi
  done
fi

docker compose --env-file "\$ENV_FILE" \
  -f "\$REPO_ROOT/infra/docker-compose.yml" \
  -f "\$COMPOSE_OVERRIDE" down
EOF
  chmod +x "$STOP_SCRIPT"
  export STOP_SCRIPT
}

