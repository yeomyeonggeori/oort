    echo "- git head: $(git -C "$REPO_ROOT" rev-parse --short HEAD)"
    echo "- mode: $MODE"
    echo "- hermes mode: $HERMES_MODE"
    echo "- external runtime smoke: $EXTERNAL_SMOKE"
    echo "- AWS resources: none; this runner does not call aws or create cloud resources."
    echo "- env file: $ENV_FILE"
    echo "- evidence dir: $EVIDENCE_DIR"
    echo
    echo "## URLs"
    echo
    echo "- MomoServer health: http://127.0.0.1:${PORT}/health"
    echo "- MomoServer REST base: http://127.0.0.1:${PORT}"
    echo "- Centrifugo HTTP: http://127.0.0.1:${CENT_PORT}"
    echo "- Centrifugo WebSocket: ws://127.0.0.1:${CENT_PORT}/connection/websocket"
    if [ "$HERMES_MODE" = "mock" ]; then
      echo "- mock Hermes health: http://127.0.0.1:${HERMES_PORT}/health"
      echo "- mock Hermes base: ${HERMES_BASE_URL}"
    else
      echo "- external Hermes base: $(redact_url "$HERMES_BASE_URL")"
