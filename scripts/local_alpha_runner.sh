    echo "- docker ps: $LOG_DIR/docker-ps.log"
    echo "- migrate: $LOG_DIR/migrate.log"
    echo "- rls prep: $LOG_DIR/verify-rls.log"
    echo "- server: $LOG_DIR/server.log"
    echo "- relay: $LOG_DIR/relay.log"
    echo "- worker: $LOG_DIR/worker.log"
    if [ "$HERMES_MODE" = "mock" ]; then
      echo "- mock Hermes: $LOG_DIR/mock-hermes.log"
    fi
    echo "- macOS smoke: $LOG_DIR/macos-smoke.log"
    echo
    echo "## macOS Dev Launch"
    echo
    echo '```sh'
