#!/usr/bin/env sh
# =============================================================================
# scripts/local_alpha_runner.sh — MOMO-240 local internal alpha runner
#
# Plan mode prints the exact local flow without starting anything.
# Execute mode starts a local Docker stack plus host-run Swift services, writes
# logs/evidence outside the repository by default, and prints the URLs/env/logs
# an alpha tester should inspect.
#
# No AWS/cloud resources are created. Secret env files must be absolute paths
# outside the repo. If no secret file is supplied in mock Hermes mode, the runner
# creates a dev-only env file in the evidence directory, also outside the repo.
# =============================================================================
set -eu

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
REPO_ROOT=$(CDPATH='' cd -- "$SCRIPT_DIR/.." && pwd)

MODE=plan
HERMES_MODE=mock
SECRET_ENV_FILE=
EXTERNAL_SMOKE=0
TMP_BASE=${TMPDIR:-/tmp}
TMP_BASE=${TMP_BASE%/}
EVIDENCE_ROOT=${LOCAL_ALPHA_EVIDENCE_ROOT:-$TMP_BASE/momo-local-alpha}
KEEP_RUNNING=1
API_PROXY_HOST=${LOCAL_ALPHA_API_PROXY_HOST:-host.docker.internal}

usage() {
  cat <<'EOF'
Usage:
  scripts/local_alpha_runner.sh plan [options]
  scripts/local_alpha_runner.sh execute [options]

Modes:
  plan | --plan | --dry-run
      Print the flow, URLs, env source, and evidence layout. Does not start
      Docker or Swift processes.

  execute | --execute
      Start Docker PG18+Centrifugo, run migrations/RLS prep, start optional
      mock Hermes, start MomoServer/OutboxRelay/AgentWorker, run macOS smoke,
      and write evidence/logs.

Options:
  --hermes mock|external
      mock starts scripts/mock_hermes.py locally. external only verifies
      HERMES_BASE_URL/HERMES_API_KEY are set in --secret-env and does not probe
      the provider unless --external-smoke is also set.

  --external-smoke
      With --hermes external, delegate to scripts/verify_external_agent_provider.sh
      for the OpenAI-compatible SSE preflight plus one
      channel message -> agent run -> external runtime -> agent response
      roundtrip. Requires --secret-env outside the repo.

  --secret-env /absolute/path/outside/repo.env
      Secret env file to source. Must be outside this repository. Required for
      --hermes external. Optional for mock mode.

  --evidence-root /absolute/or/relative/path
      Root directory for evidence run folders. Defaults to
      ${TMPDIR:-/tmp}/momo-local-alpha.

  --stop-after-smoke
      Execute the flow, then stop host Swift/mock processes and Docker compose.
      Default execute behavior leaves the local alpha stack running and prints a
      stop command.

  --api-proxy-host host.docker.internal
      Hostname Centrifugo should use from inside Docker to call the host-run
      MomoServer subscribe proxy. Defaults to host.docker.internal.

Examples:
  scripts/local_alpha_runner.sh plan
  scripts/local_alpha_runner.sh execute --hermes mock
  scripts/local_alpha_runner.sh execute --hermes external --secret-env "$HOME/.momo/local-alpha.env"
  scripts/local_alpha_runner.sh execute --hermes external --external-smoke --secret-env "$HOME/.momo/external-agent.env"
EOF
}

fail() {
  echo "[local-alpha] ERROR: $*" >&2
  exit 1
}

abs_existing_file() {
  path=$1
  case "$path" in
    /*) ;;
    *) fail "path must be absolute: $path" ;;
  esac
  [ -f "$path" ] || fail "file not found: $path"
  dir=$(dirname -- "$path")
  base=$(basename -- "$path")
  dir_abs=$(CDPATH='' cd -- "$dir" && pwd -P)
  printf '%s/%s\n' "$dir_abs" "$base"
}

abs_dir_path() {
  path=$1
  case "$path" in
    /*) printf '%s\n' "$path" ;;
    *) printf '%s/%s\n' "$(pwd -P)" "$path" ;;
  esac
}

assert_secret_env_outside_repo() {
  file=$1
  case "$file" in
    "$REPO_ROOT"|"$REPO_ROOT"/*)
      fail "--secret-env must be outside the repo: $file"
      ;;
  esac
}

require_cmd() {
  if ! command -v "$1" >/dev/null 2>&1; then
    fail "missing required command: $1"
  fi
}

redact_url() {
  printf '%s' "$1" | sed -E 's#//([^/:@]+):([^@]+)@#//***:***@#g'
}

print_redacted_env_value() {
  key=$1
  value=${2:-}
  case "$key" in
    *PASSWORD*|*KEY*|*HMAC*|*TOKEN*|*SECRET*)
      if [ "$value" = "" ]; then
        printf '<unset>'
      else
        printf '<set:redacted>'
      fi
      ;;
    *URL*)
      redact_url "$value"
      ;;
    *)
      printf '%s' "$value"
      ;;
  esac
}

