// 전역 이동 단축키를 잠시 멈춘다 (#4663 보안·디자인 검수 High).
//
// 한 번만 보이는 값(연결 값처럼 서버가 해시만 쥐고 있어 다시 만들 수 없는 것)이 화면에 떠 있는 동안은,
// 창에 걸린 이동 단축키(⌘⇧A 받은 편지함, ⌘K 팔레트, ⌘⇧K 새 다이렉트 메시지, ⌥↑·⌥↓ 안 읽은 채널)가 그 값을
// 쥔 화면을 말없이 떠나게 해서는 안 된다. 모달은 창의 keydown 을 막지 않는다. 폼 다이얼로그 넷은 각자의 열림
// 상태를 컨텍스트로 내보내 이 키들이 물러서게 하지만(R2 M4), 값 화면은 그 목록에 없었고, 키 한 번이면 설정
// 라우트가 내려가며 값이 사라졌다.
//
// 값을 쥔 화면이 `holdGlobalShortcuts()`를 부르고, 창에 걸린 이동 단축키 핸들러가 키를 받을 때
// `globalShortcutsHeld()`를 읽어 물러선다. 렌더에 묶지 않고 키가 눌린 그 순간 읽는다: 재렌더를 기다리는 사이에
// 키가 지나갈 틈이 없다.
//
// 이 멈춤이 막지 않는 것: 브라우저의 뒤로 가기와 주소 편집. 이 앱의 라우터는 `HashRouter`(데이터 라우터가
// 아니라서 `useBlocker`가 없다)라 화면이 막을 수 없다. 값 화면의 나가는 길이 「저장했어요」 하나라는 약속은
// 앱 안의 길(목차·단축키·Esc·바깥 클릭)에 대한 것이다.
// =============================================================================

let holds = 0;

/** 멈춤을 건다. 돌려받은 함수가 푼다. 같은 걸이로 두 번 불러도 한 번만 풀린다. */
export function holdGlobalShortcuts(): () => void {
  let released = false;
  holds += 1;
  return () => {
    if (released) return;
    released = true;
    holds -= 1;
  };
}

/** 지금 이동 단축키를 멈춰야 하는가. 키가 눌린 순간에 읽는다. */
export function globalShortcutsHeld(): boolean {
  return holds > 0;
}
