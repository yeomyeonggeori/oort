// 다시 실행하기 전에 쓰던 글을 저장소로 내린다 (성재 결재 2026-10-16: 「업데이트
// 후에 자동으로 다시 실행」).
//
// 자동으로 다시 실행하면 앱이 스스로 사라진다. 사람은 그 순간 무엇을 쓰고 있었는지
// 알 수 없으므로, 안 보낸 글은 프로세스가 끝나기 전에 디스크에 있어야 한다.
// 채널 컴포저는 입력마다 `draftStore` 에 쓰고, 스레드 컴포저는 메모리에만 들고 있다.
// 그래서 한 문(門)을 둔다: 다시 실행 직전에 이 이벤트를 **동기로** 던지고, 글을 가진
// 쪽이 같은 틱 안에서 `localStorage` 에 쓴다. 이벤트는 동기 디스패치이고 `setItem` 도
// 동기이므로, 이 함수가 돌아온 시점에는 쓰기가 끝나 있다.
// =============================================================================

export const BEFORE_RELAUNCH_EVENT = "momo:before-relaunch";

/** 쓰던 글을 가진 모든 입력창에게 「지금 저장하세요」를 알린다. 돌아오면 저장이 끝난 것이다. */
export function flushBeforeRelaunch(): void {
  if (typeof window === "undefined") return;
  try {
    window.dispatchEvent(new Event(BEFORE_RELAUNCH_EVENT));
  } catch {
    /* 한 입력창의 실패가 다시 실행을 막지 않는다. 리스너는 각자 try/catch 를 둔다. */
  }
}
