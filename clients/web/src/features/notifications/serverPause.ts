// 서버의 알림 일시 중지, 이 기기의 OS 배너 길목이 함께 읽는 값 하나 (#4197).
//
// 폰 푸시는 서버 `judge_targets` 가 `notification_rule.dnd` 로 멈춘다(ADR-0124 증보 2). 데스크탑·웹의
// OS 배너는 서버를 거치지 않고 이 기기가 `message.new` 로 스스로 판정해 왔고, 그 입력에 일시 중지가
// 없었다 — 「알림도 함께 멈춰요」라고 말한 화면의 사용자 옆에서 배너만 계속 떴다(성재 0.1.32 실기).
//
// 이 값을 읽는 배너 길목은 둘이다: 메시지 레일(`notifyThisDevice` → core `notifyDecision`)과 로컬 칸
// 알림(`paneAttention`). 둘이 **같은 값**을 읽도록 한 곳에 둔다. 값을 가져오고 새로 읽는 쪽은 훅
// (`useServerPause.ts`)이고, 이 파일은 React 도 질의 클라이언트도 모른다 — 순수한 판정 모듈(`deviceNotify`)
// 과 칸 저장소(`paneAttention`)가 질의 그래프를 끌고 들어오지 않게 한다.
//
// **이 값을 읽지 않는** OS 배너 길목도 둘 있다. 의도한 면제가 아니라 이 단계(#4197)의 범위 밖이고, 수용 기준이
// 메시지 배너와 칸 알림만 적었기 때문이다. 일시 중지 중에도 이 둘은 뜬다:
//   - 나중에 알림(`reminders/dueNotify.ts`): 사람이 잡아 둔 시각의 알림이라 서버 푸시가 없다. 기한이 된 알림을
//     「일시 중지라 건너뜀」으로 처리하면 풀린 뒤에도 다시 뜨지 않는다(`announcedIds`·워터마크가 먼저 지나간다).
//     일시 중지 아래에 둘지, 풀린 뒤 한 번 몰아 알릴지는 결정이 필요한 후속이다.
//   - 작업 호스트 등록 고지(`WorkHostNotices.tsx`): 내 이름으로 호스트가 등록됐다는 보안 사실이다(ADR-0188 D2 「모든
//     기기에 알린다」). 이번 단계에서는 읽지 않는다.
// 새 OS 배너 길목을 만들 때는 이 값을 읽을지 여기서 대조해 정한다.
//
// 값의 뜻은 하나다: **서버가 마지막으로 답한 규칙의 `dnd`(유효 값)**. 기한을 이 기기 시계와 비교해 풀지
// 않는다 — 만료는 서버가 판정하고 클라이언트는 다시 읽을 뿐이다(ADR-0204 D3). 한 번도 못 읽었으면
// 거짓이다: 읽지 못한 규칙으로 배너를 막으면 조용히 사라지는 알림이 된다(ADR-0204가 고친 15일간의 무음과 같은 모양).
// =============================================================================

let paused = false;

/** 서버가 마지막으로 답한 알림 일시 중지. 한 번도 못 읽었거나 읽을 수 없는 표면이면 거짓이다. */
export function serverPauseActive(): boolean {
  return paused;
}

/** 훅이 서버의 새 답을 넣는다. 다른 곳에서 부르지 않는다(시험은 예외). */
export function setServerPause(next: boolean): void {
  paused = next;
}
