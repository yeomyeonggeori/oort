// =============================================================================
// 「다른 워크스페이스로 들어가는 길」의 낱말과 문장 (#4198, 멀티 조직 P0-A).
//
// 로그인 화면이 실제로 받는 것은 워크스페이스 **ID(UUID)** 다. 「다른 워크스페이스로
// 로그인」을 펼치면 「워크스페이스 ID」 칸이 나오고, 서버(`resolve_login_workspace`,
// `server-rust/bins/momo-server/src/routes/auth_routes.rs`)는 슬러그를 400으로 거절한다.
// 그런데 새 워크스페이스를 만든 직후 완료 패널은 슬러그로 다시 로그인하라고 말하면서
// ID는 보여 주지도 않았다: 안내가 가리키는 길이 실제 화면에 없는 막다른 길이었다.
//
// 그 모양이 다시 생기지 않게, 길의 **이름**을 로그인 화면(`ConnectPage`)과 안내 문장이
// 한 자리에서 받는다. 화면 글자를 고치면 안내도 같이 따라간다.
//
// 같은 문장을 두 자리가 쓴다: 레일 「+」 다이얼로그의 완료 패널(`AddWorkspaceDialog`)과
// 설정 › 워크스페이스의 완료 카드(`WorkspaceSection`). 같은 사실을 같은 문장으로 말한다.
//
// 슬러그 로그인(멀티 조직 P1-A)이 서버에 들어오면 이 문장을 다시 쓴다.
// =============================================================================

/** 로그인 화면의 접힘 단추 글자. */
export const LOGIN_OTHER_WORKSPACE_LABEL = "다른 워크스페이스로 로그인";

/** 접힘 단추를 펼치면 나오는 칸의 이름. */
export const LOGIN_WORKSPACE_ID_LABEL = "워크스페이스 ID";

/**
 * 새 워크스페이스를 만든 직후, 어떻게 들어가는지 한 문장으로 말한다. 세션 전환이 없어서
 * 만든 워크스페이스에는 로그아웃한 뒤 로그인 화면으로만 들어간다(ADR-0161 4b-3 미착수).
 * 「이 ID」는 같은 화면에 보이는 「워크스페이스 ID」 줄이다.
 */
export const NEW_WORKSPACE_ENTRY_GUIDE = `들어가려면 로그아웃한 뒤 로그인 화면에서 「${LOGIN_OTHER_WORKSPACE_LABEL}」을 열고, ${LOGIN_WORKSPACE_ID_LABEL} 칸에 이 ID를 붙여 넣어요.`;

/**
 * 이 ID는 만든 응답에서만 나온다: 워크스페이스 목록 API도, 다시 보여 주는 화면도 없다(세션 전환·
 * 계정 집합은 멀티 조직 P1). 그래서 화면을 벗어나기 전에 복사하라고 먼저 말한다. 한 번만 보이는
 * 값을 말하는 집의 문장과 같은 결이다(웹훅 발급 카드 「이 화면을 벗어나면 다시 볼 수 없어요」).
 */
export const NEW_WORKSPACE_ID_ONCE_NOTICE =
  "이 화면을 벗어나면 ID를 다시 볼 수 없으니 지금 복사해 두세요.";

// 두 완료 표면의 자리: 경고(`NEW_WORKSPACE_ID_ONCE_NOTICE`)는 값보다 **앞**, 늘 보이는 자리에 선다
// (레일 패널은 고정 머리의 설명, 설정 카드는 카드 위 설명). 방법(`NEW_WORKSPACE_ENTRY_GUIDE`)은
// 값 **뒤**다. 한 번만 보이는 값의 집 모양이 경고가 값보다 앞이기 때문이고, 경고가 값 뒤에 서면
// 낮은 창에서 접힌 아래로 사라져 「왜 Esc가 안 닫히나」의 이유가 보이지 않는다(design-review 3차 H1).
