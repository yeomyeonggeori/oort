// =============================================================================
// 본문 칸을 만들 것인가 (이슈 #1465).
//
// 이 행은 두 가지를 묻는다. 첫 물음은 코어의 것이다 — **자격**: 이 행의 카드가 이미
// 자기 제목과 행으로 본문을 말해 버렸는가(`cardKeepsBody`). 승인 카드와 도구 카드는
// 그렇고, 요약 없는 완료 리포트는 아니다("본문이 곧 빠진 요약이다", agentCardModel).
//
// 두 번째 물음은 표면의 것이고 여기 있다 — **살릴 본문이 실제로 있는가.** 웹은 그것을
// 묻지 않고 `body ?? ""` 를 그대로 `MessageBody` 에 넘겼다. `MessageBody` 의 plain
// 갈래는 무엇을 받든 문단을 하나 만들므로, 본문이 없는 행에도 `<p>` 가 하나 섰다.
// 폰은 같은 자리에서 `body !== ''` 로 칸을 아예 만들지 않는다(`clients/mobile/.../
// MessageRow.tsx`). 두 클라가 같은 얼굴을 갖는다는 약속이 여기서 갈라져 있었다.
//
// ## 실측 (게이트만 실린 리포트, 1280×900, `capture-completion.mjs`)
//
// | body            | `<p>` | 높이 |
// |-----------------|-------|------|
// | 키 자체가 없음   | 있음  | 0px  |
// | `""`            | 있음  | 0px  |
// | `"   \n  "`     | 있음  | 46px |
//
// 부재와 빈 문자열에서 그 문단은 **자리를 차지하지 않는다**. 빈 블록에는 줄상자가
// 생기지 않기 때문이고, 그래서 #1454 가 지금 커밋하는 모양(본문 키 부재)에서 눈에
// 보이는 어긋남은 없다 — 남는 것은 행 안의 문단 노드 하나다. 눈이 보는 결함은
// **공백만 있는 본문**에 있다: `whitespace-pre-wrap` 이 그 공백을 그대로 그려서 카드
// 위에 빈 줄 두 개(46px)가 선다.
//
// 그래서 판정은 `trim()` 으로 한다. 폰의 `body !== ''` 보다 한 칸 넓고, 넓은 쪽이
// 옳다: 사람이 읽을 글자가 없다는 사실은 공백의 개수와 무관하다.
//
// 묘비와 편집기는 이 판정을 거치지 않는다(`MessageRow`). 둘 다 본문 자리에 서지만
// 본문이 아니다 — 묘비는 지워진 본문에 **대한** 앱의 서술이고, 편집기는 빈 본문에서
// 특히 필요한 입력 상자다.
// =============================================================================

/**
 * 사람이 읽을 글자가 이 본문에 있는가.
 *
 * `null` 도 받는다. 타입은 `body?: string` 이지만 실시간 프레임은 `"body": null` 을
 * 싣고(`momo_messaging::build_broadcast_payload`), 그 `null` 을 부재로 바꾸는 것은
 * 코어의 `payloadToMessage` 다. 그 정규화 하나에 화면 판정을 기대지 않는다.
 */
export function hasRenderableBody(body: string | null | undefined): boolean {
  return (body ?? "").trim() !== "";
}
