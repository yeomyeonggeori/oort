// =============================================================================
// 설정 폼 노드의 id 규약 (#1559 회전 1 · design-review #1595 M5).
//
// 컴포넌트 파일(`SettingsFields.tsx`)이 아니라 여기 사는 이유는 두 가지다.
//
//   * Fast refresh: 그 파일은 컴포넌트만 내보낸다(`react-refresh/
//     only-export-components`). 형제 `webhookCredentialScope.ts`·`oauthGrant.ts`
//     가 같은 이유로 같은 자리에 있다.
//   * 이 규약의 소비자는 컴포넌트 **밖**이다. id 를 필요로 하는 쪽은 그 노드를
//     그리는 컴포넌트가 아니라, 그 문장을 자기 사유로 **가리키는** 다른 컨트롤이다.
// =============================================================================

/**
 * `ChoiceRadios` 가 그룹 아래에 그리는 상태 문장의 id — 상속 중 / 저장 중 /
 * 아직 저장되지 않음.
 *
 * 그 문장은 그룹만의 것이 아니다: 쓰기가 나는 동안 그것은 같은 블록의 **다른**
 * 컨트롤이 잠긴 이유이기도 하다(저장 버튼 옆의 되돌리기). 잠금 하나에 문장 하나,
 * 그 하나를 가리키는 컨트롤은 여럿 — 컨트롤마다 되풀이하면 같은 사실이 한 화면에
 * 여러 번 선다.
 *
 * 그래서 규약에 주인이 하나 있어야 한다. 호출부가 `${name}-hint` 를 손으로 다시
 * 지으면 그것은 규약의 두 번째 사본이고, 조용히 낡는다.
 */
export function choiceRadiosHintId(name: string): string {
  return `${name}-hint`;
}
