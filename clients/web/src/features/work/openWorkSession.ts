/**
 * 한 화면에서 다른 화면의 한 자리를 가리키는 동작 하나 (LIVE-5b).
 *
 * ## 왜 새 액션이 아니라 이 액션의 인자인가
 *
 * 타임라인에서 작업 세션으로 가는 길은 이미 있었다 — 로그인 핸드오프 카드의
 * 「작업 세션 열기」와 유휴 세션 카드의 같은 동작. LIVE-5 가 더한 것은 **새로운
 * 목적지가 아니라 도착한 뒤의 자세**다: 같은 세션 상세인데, 사람이 그 화면에서
 * 하려던 일이 관전이 아니라 조작이다.
 *
 * 그것을 두 번째 액션으로 만들면 카드에 버튼이 하나 더 서고, 두 버튼이 **같은
 * 곳으로 간다**. 화면이 두 개의 문을 그리는데 뒤에 방은 하나이면, 읽는 사람은
 * 자기가 고른 문에 따라 다른 곳에 도착한다고 믿는다.
 *
 * ## 의도이지 약속이 아니다
 *
 * `control` 은 도착지에서 **확인 단계를 무장**할 뿐 창을 열지 않는다. 링크가
 * 눌렸다는 사실만으로 남의 에이전트가 멈추면 안 되고, 애초에 보내는 쪽은 이
 * 사람이 그 세션의 소유자인지 알지 못한다(카드 props 에 소유자가 없다 —
 * `loginHandoffSeeksControl` 의 주석이 왜 없어야 하는지까지 적어 두었다).
 * 어포던스를 세울지 말지는 소유자를 아는 쪽, 즉 도착지가 정한다.
 *
 * 인자가 **선택적**인 것도 계약의 일부다. 이 손잡이를 이미 쥐고 있던 호출자들
 * (`WorkSessionIdleCard` 의 `onOpen`)은 한 글자도 바뀌지 않는다.
 */
export interface OpenWorkSessionIntent {
  /** 도착지에서 직접 조작 확인 단계를 무장한다. 창을 열지는 않는다. */
  control: boolean;
}

export type OpenWorkSession = (
  sessionId: string,
  intent?: OpenWorkSessionIntent
) => void;
