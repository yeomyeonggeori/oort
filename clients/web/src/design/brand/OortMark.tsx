// =============================================================================
// oort 마크 (B4.4). 제품 이름 표기가 momo에서 oort로 바뀌면서 이 클라이언트가
// 처음으로 갖는 자기 표식이다. 코드 식별자·API·딥링크 스킴은 그대로다: 바뀐 것은
// 사람이 읽는 문자열과 이 그림뿐이다.
// icon-system-exception(ADR-0172): Lucide에 없는 oort 브랜드 마크라 로컬 SVG로
// 남긴다. 기능 아이콘으로 재사용하지 않는다.
//
// 형태는 세 조각이고 각각 이름이 있다.
//   O    — 말풍선이기도 한 고리. 메신저라는 사실이 먼저 읽혀야 하므로 꼬리가
//          장식이 아니라 윤곽선의 일부다(획 하나로 이어진 닫힌 path).
//   궤도 — O 뒤로 지나가는 타원. **고리와 겹치는 구간은 그리지 않는다.** 처음
//          시안은 타원을 통째로 얹었는데, 24px에서 안쪽을 가로지르는 두 선이
//          말풍선을 덩어리로 만들었다. 바깥 두 토막만 남기면 "뒤로 지나간다"는
//          읽기는 유지되고 안쪽은 비어 있다.
//   (없음)— 궤도 위의 점은 뺐다. 말풍선 우상단의 점은 모든 메신저에서 안 읽은
//          표시이고, 로고가 뱃지 흉내를 내면 안 된다.
//
// 색은 `currentColor` 하나다. 라이트/다크 두 벌을 두지 않고 부모가 정한 잉크를
// 물려받으므로, 사이드바에서는 --accent, 잠금화면 락업에서는 같은 --accent,
// 비활성 자리에서는 --ink-muted가 그대로 걸린다(tokens.css가 유일한 색 출처).
//
// 참고 컨셉(다크 배경 + 파랑~보라 그라디언트)에서 **형태만** 가져왔다. 그 색은
// 이 제품이 쓸 수 없다: 팔레트에서 indigo/violet 대역은 비워져 있고(bg-indigo-*는
// 컴파일되지 않는다), 파랑은 --agent가 이미 에이전트 정체성으로 쓰고 있다.
// 로고가 --agent 근처 색을 입으면 "이 화면은 에이전트의 것"이라는 신호와
// 제품 표식이 같은 색으로 겹친다. 그래서 마크는 액센트(호박)를 쓴다.
// =============================================================================

/**
 * 24x24 그리드의 oort 마크. 크기는 호출자가 유틸리티로 정한다(`size-4`,
 * `size-6`) — lucide 아이콘과 같은 규격·같은 획 두께라 나란히 서도 어긋나지
 * 않는다.
 *
 * 기본은 `aria-hidden`이다. 마크는 거의 언제나 바로 옆의 "oort"라는 글자나
 * 이미 이름이 있는 컨트롤을 꾸미는 자리에 서기 때문에, 접근성 트리에 이름을
 * 한 번 더 얹으면 스크린리더가 같은 단어를 두 번 읽는다. 마크가 **혼자**
 * 제품을 가리키는 자리(창 좌상단 홈 타일)에서만 `title`을 넘긴다.
 */
export function OortMark({
  className,
  title,
}: {
  className?: string;
  /** 넘기면 접근 가능한 이름이 되고, 넘기지 않으면 장식으로 감춰진다. */
  title?: string;
}) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : "true"}
    >
      {/* O + 말풍선 꼬리: 320도 호를 돈 뒤 꼭짓점으로 내려가 닫는다. */}
      <path d="M9.9 16.92A6.2 6.2 0 1 0 5.93 13.81L4.38 19.88Z" />
      {/* 궤도의 바깥 두 토막. 고리 반지름 + 0.5px만큼 비켜서 시작하므로 획이
          맞닿는 지점에서 뭉치지 않는다. */}
      <path d="M15.89 5.92A10.4 3.6 -22 0 1 18.08 11.36M6.91 15.88A10.4 3.6 -22 0 1 4.72 10.44" />
    </svg>
  );
}
