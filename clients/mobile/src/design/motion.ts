/** UI 진입·퇴장의 강한 ease-out. `ease-in` 은 쓰지 않는다 — 보는 순간을 늦춘다. */
export const EASE_OUT = Easing.bezier(0.23, 1, 0.32, 1);

/** 탭 콘텐츠가 드러나는 시간. 하루 수백 번 보는 전환이라 150ms 를 넘기지 않는다. */
export const TAB_FADE_MS = 150;

/**
 * 착지 틴트("방금 여기로 왔다")가 물러나는 시간 (#3921). 곡선은 `EASE_OUT`.
 *
 * 오르트 구름의 모션 사다리 `standard`(웹 `--motion-standard` 240ms — 「상태 변화」)다.
 * 행이 「방금 도착한 행」에서 「평범한 행」이 되는 상태 변화로 읽었다. 사다리 밖 값은
 * 들이지 않는다.
 *
 * 알아 둘 것 둘.
 *   - 눈에 남는 페이드는 240ms 가 아니라 앞쪽이다. 강한 ease-out 은 앞에서 많이 빠져
 *     (60ms 에 77%, 90ms 에 91%, 120ms 에 97%) 나머지는 보이지 않는 꼬리다. 이 요소가 색
 *     변화에 가깝다고 읽으면 한 칸 아래 `instant`(120ms, 「눌림·색·툴팁」)가 맞고, 그러면 눈에
 *     남는 길이는 60ms 안팎이 된다. 「부드럽게」가 이슈의 말이라 `standard` 를 택했다. 길이를
 *     바꾸고 싶으면 사다리의 다른 칸을 고르는 판단이지 값을 새로 지어내는 일이 아니다.
 *     다만 이 틴트는 바닥과의 대비가 1.11~1.30:1 로 옅어 눈에 남는 앞 60~90ms 가 사실상
 *     전부다 — 「부드럽게」보다 「빠른 꺼짐」으로 읽힐 수 있다(실기기 미확인).
 *   - 사다리의 「사라짐은 나타남보다 짧다」(비대칭 문단, 모달 열림 200 / 닫힘 150)는 이
 *     요소에서 **반대로 간다.** 이 틴트의 나타남은 0ms 스냅이다 — 표시를 먼저 세우고
 *     스크롤한다(`Timeline` 점프 효과). 0 들어옴 / 240 나감이다. 그 문단은 모달 한 쌍을 사례로
 *     드는 일반문이고, 나타남이 스냅인 표시는 다루지 않는다 — 그래서 이 값은 비대칭 규칙에서
 *     나온 것이 아니라 표의 `standard` 칸을 그대로 쓴 것이다. 폰 모션 값은 기계가 재지 않는다
 *     (README 「폰 모션·밀도 값 파생 + 바이트 대조」, M1a 미완). 「사다리 밖 값은 들이지 않는다」는
 *     검사가 아니라 이 주석의 약속이고, 240 은 손으로 쓴 숫자다.
 *
 * 「동작 줄이기」면 이 시간이 0 이 된다 — 사다리 D9(「모션을 끄는 것이 아니라 0으로
 * 만든다, 상태는 착지한다」). 머무는 시간은 그대로다(`LandedTintFade`).
 */
export const LANDED_TINT_FADE_MS = 240;

// =============================================================================
// 첨부 메뉴 (#4180) — + 원에서 카드가 펼쳐지고, 접혀 들어간다.
//
// 크기·불투명도를 **스프링 하나**(진행값 0→1)가 끈다. 곡선이 아니라 물리라서 열리는 도중에
// 닫아도 속도가 이어진다(`Animated.spring` 은 현재 속도에서 출발한다). 값은 시간표(사다리)가
// 아니라 감쇠비로 정한다: 감쇠비 1(임계감쇠)이면 넘침이 없고, 눈에 보이는 길이는 98% 에
// 닿는 때다 — ωt ≈ 5.83, ω = √(stiffness/mass).
//
//   열림   380 / 39 / 1 → ω 19.5 → 98% 에 ≈ 300ms. 탭 캡슐(`CAPSULE_SPRING`)과 같은 값이라
//          앱의 「자리를 옮기는 스프링」이 한 가지 느낌이다. 이슈의 「겉보기 ~250–350ms」 안이다.
//   닫힘   680 / 52 / 1 → ω 26.1 → 98% 에 ≈ 225ms. 사다리의 「사라짐은 나타남보다 짧다」.
//
// 감쇠비는 시험이 잰다: damping / (2·√(stiffness·mass)) ≥ 0.99 (`attachMenu.test.tsx`).
// 그래도 `overshootClamping` 을 켠다 — 값이 1 을 넘으면 카드가 제 크기보다 커진다.
// =============================================================================

/** 메뉴가 펼쳐질 때의 스프링. 감쇠비 1: 2·√380 ≈ 39. */
export const MENU_OPEN_SPRING = {stiffness: 380, damping: 39, mass: 1} as const;

/** 메뉴가 접힐 때의 스프링. 감쇠비 ≈ 0.997: 2·√680 ≈ 52. */
export const MENU_CLOSE_SPRING = {stiffness: 680, damping: 52, mass: 1} as const;

/**
 * 접힘이 「끝났다」고 알리는 문턱. 기본값(0.001)이면 눈에 안 보이는 꼬리를 ≈ 640ms 까지
 * 기다린다 — 그 뒤에야 Modal 이 내려가고 picker 가 뜨므로 사람이 느끼는 지연이 된다. 진행값이
 * 0.02 밑이면 카드는 시작 크기의 2% 안이고 불투명도는 이미 7% 밑이다.
 */
export const MENU_CLOSE_REST = {
  restDisplacementThreshold: 0.02,
  restSpeedThreshold: 0.5,
} as const;

/**
 * 「동작 줄이기」의 페이드 길이 — 크기 애니메이션 없이 불투명도만. 사다리 `fast`(180ms,
 * 「작은 표면 — 팝오버·드롭다운·칩」)다. 곡선은 `EASE_OUT`.
 */
export const MENU_FADE_MS = 180;

