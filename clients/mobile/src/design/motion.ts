// 첨부 메뉴 (#4180) — + 원에서 카드가 펼쳐지고, 접혀 들어간다.
//
// 크기·불투명도를 **스프링 하나**(진행값 0→1)가 끈다. 곡선이 아니라 물리라서 열리는 도중에
// 닫아도 속도가 이어진다(`Animated.spring` 은 현재 속도에서 출발한다). 값은 시간표(사다리)가
// 아니라 감쇠비로 정한다: 감쇠비 1(임계감쇠)이면 넘침이 없고, 눈에 보이는 길이는 98% 에
// 닿는 때다 — ωt ≈ 5.83, ω = √(stiffness/mass).
//
//   열림   380 / 39 / 1 → ω 19.5 → 98% 에 ≈ 300ms. 탭 캡슐(`CAPSULE_SPRING`)과 같은 값이라
//          앱의 「자리를 옮기는 스프링」이 한 가지 느낌이다. 이슈의 「겉보기 ~250–350ms」 안이다.
//   닫힘   680 / 52 / 1 → ω 26.1 → 98% 에 ≈ 225ms. 사다리의 「사라짐은 나타남보다 짧다」.
//
// 감쇠비는 시험이 잰다: damping / (2·√(stiffness·mass)) ≥ 0.99 (`attachMenu.test.tsx`).
// 그래도 `overshootClamping` 을 켠다 — 값이 1 을 넘으면 카드가 제 크기보다 커진다.
// =============================================================================

