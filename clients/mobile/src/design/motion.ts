// 스프링은 첫 프레임에 8%(3.5pt)로 출발해 키보드의 첫 프레임(383ms 기준 8%)과 같고, 두 길이 어느 쪽에서도 키보드와의 모양 차가 ease-out 의
// 절반 안팎 이하다. 다만 383ms 키보드보다 ~90ms 먼저 끝난다 — 맞추려면 이 스프링을 느리게 해야 하는데 그건 Buzz 값이 아니다(이슈가 고르라고 한 두 후보는
