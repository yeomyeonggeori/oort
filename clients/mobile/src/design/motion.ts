/** 등장 길이. 사다리 전용 칸 `send-arrive` — Buzz `localMessageSendTransitionDuration`(위 설명). */
export const SEND_ARRIVE_MS = 300;

/** 등장 곡선. Flutter `Curves.easeOutCubic` = `cubic-bezier(0.215, 0.61, 0.355, 1)` 그대로. */
export const SEND_ARRIVE_EASE = Easing.bezier(0.215, 0.61, 0.355, 1);

/**
 * 시작 위치가 자리보다 **아래**인 거리, 자기 높이의 배수. Buzz `localMessageSendTransitionStartOffset`.
 * 입력창이 바로 아래에 있으므로 「입력창 밑에서 올라온다」는 이 만큼의 오름이다. 크기·높이는
 * 건드리지 않는다 — 행 높이가 바뀌면 바닥 추적이 흔들린다(오름은 transform 이라 레이아웃 비용이 0).
 */
export const SEND_ARRIVE_RISE_FACTOR = 1.5;

/** 작성자 머리(아바타·이름 줄)가 서는 행의 배수. Buzz `…AvatarStartOffset`. 머리 행은 그만큼 키가 크다. */
export const SEND_ARRIVE_RISE_FACTOR_HEAD = 2.5;

/**
 * 자격 창. 보낸 지 이 시간 안에 그려진 메아리만 움직인다. Buzz
 * `_localMessageSendAnimationClaimWindow`. 늦게 그려진 내 메시지(방을 늦게 열었거나 복원된 전송)가
 * 방금 보낸 것처럼 보이면 안 된다. 기준은 마운트 시각이 아니라 **보낸 시각**(`createdAtMs`)이다.
 */
export const SEND_ARRIVE_WINDOW_MS = 1000;

/**
 * 확정본이 등장 도중에 와도 메아리를 자리에 두는 시간 = `SEND_ARRIVE_MS` + 이 값(ms) (#4455 H1, `sendArrival.ts`).
 * 네이티브 구동 애니메이션은 마운트보다 5~25ms 늦게 시작하고 마지막 프레임이 프레임 간격(≈17ms)에 걸려서 정확히
 * 300ms 에 끝나지 않는다. 이 여유가 끝난 뒤에야 서버 사본으로 바뀌므로, 바뀌는 순간 transform 은 이미 0 이다.
 */
export const SEND_ARRIVE_HOLD_SLACK_MS = 60;

/**
 * 첫 레이아웃 이벤트가 오기 전(한두 프레임)에 오프셋을 계산하는 **가정 높이**(pt). 목록의 어느
 * 행보다 크게 잡아, 높이를 재기 전에 행이 자리에 선 채 한 프레임 보이는 일이 없게 한다. 가림은
 * 스크롤뷰의 아래 가장자리가 한다. 재고 나면 실제 높이로 바뀐다.
 */
export const SEND_ARRIVE_UNMEASURED_HEIGHT = 1000;

