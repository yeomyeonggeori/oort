/**
 * 착지 틴트("방금 여기로 왔다")가 물러나는 시간 (#3921). 곡선은 `EASE_OUT`.
 *
 * 오르트 구름의 모션 사다리 `standard`(웹 `--motion-standard` 240ms — 「상태 변화」)다.
 * 행이 「방금 도착한 행」에서 「평범한 행」이 되는 상태 변화로 읽었다. 사다리 밖 값은
 * 들이지 않는다.
 *
 * 알아 둘 것 둘.
 *   - 눈에 남는 페이드는 240ms 가 아니라 앞쪽이다. 강한 ease-out 은 앞에서 많이 빠져
 *     (60ms 에 77%, 90ms 에 91%, 120ms 에 97%) 나머지는 보이지 않는 꼬리다. 이 요소가 색
 *     변화에 가깝다고 읽으면 한 칸 아래 `instant`(120ms, 「눌림·색·툴팁」)가 맞고, 그러면 눈에
 *     남는 길이는 60ms 안팎이 된다. 「부드럽게」가 이슈의 말이라 `standard` 를 택했다. 길이를
 *     바꾸고 싶으면 사다리의 다른 칸을 고르는 판단이지 값을 새로 지어내는 일이 아니다.
 *     다만 이 틴트는 바닥과의 대비가 1.11~1.30:1 로 옅어 눈에 남는 앞 60~90ms 가 사실상
 *     전부다 — 「부드럽게」보다 「빠른 꺼짐」으로 읽힐 수 있다(실기기 미확인).
 *   - 사다리의 「사라짐은 나타남보다 짧다」(비대칭 문단, 모달 열림 200 / 닫힘 150)는 이
 *     요소에서 **반대로 간다.** 이 틴트의 나타남은 0ms 스냅이다 — 표시를 먼저 세우고
 *     스크롤한다(`Timeline` 점프 효과). 0 들어옴 / 240 나감이다. 그 문단은 모달 한 쌍을 사례로
 *     드는 일반문이고, 나타남이 스냅인 표시는 다루지 않는다 — 그래서 이 값은 비대칭 규칙에서
 *     나온 것이 아니라 표의 `standard` 칸을 그대로 쓴 것이다. 폰 모션 값은 기계가 재지 않는다
 *     (README 「폰 모션·밀도 값 파생 + 바이트 대조」, M1a 미완). 「사다리 밖 값은 들이지 않는다」는
 *     검사가 아니라 이 주석의 약속이고, 240 은 손으로 쓴 숫자다.
 *
 * 「동작 줄이기」면 이 시간이 0 이 된다 — 사다리 D9(「모션을 끄는 것이 아니라 0으로
 * 만든다, 상태는 착지한다」). 머무는 시간은 그대로다(`LandedTintFade`).
 */
export const LANDED_TINT_FADE_MS = 240;

