// 이제 펼침은 **포커스와 함께** — iOS 키보드가 오르는 바로 그때 — 시작한다. 알약의 아래는 키보드 윗면에 붙어 있어서 윗면은 키보드와 함께
// 오르면서 펼침만큼 더 오른다. 두 움직임이 한 동작으로 읽히려면 모양과 끝나는 때가 같아야 한다. 키보드 곡선(`useKeyboard.ts` `KEYBOARD_EASING`
// = bezier(0.38, 0.7, 0.125, 1), 길이는 `keyboardWillShow` 이벤트가 준다)과 두 후보를 같은 표로 쟀다(진행값 0→1, 16ms 표본). **키보드 길이는
