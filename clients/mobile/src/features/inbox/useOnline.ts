import NetInfo from '@react-native-community/netinfo';
import {useEffect, useState} from 'react';
import {isOnlineFromNetInfo} from '../../query/queryClient';

// =============================================================================
// 결정을 지금 보낼 수 있는가
// =============================================================================
//
// 승인 컨트롤이 서는 화면이 둘이 됐고(인박스 · 타임라인 승인 카드), 같은 결정
// 컨트롤이 화면마다 다른 오프라인 결을 가지면 그것은 어휘 분열이다. 배선을
// 한 곳에 둔다 — 인박스가 손으로 들고 있던 `useState` + `addEventListener` 를
// 그대로 옮겼다.
//
// ## 왜 실시간 레일 상태가 아닌가
//
// 대화 화면은 이미 연결 신호 하나를 들고 있다(`useRealtime()` 의 `status`).
// 새 구독을 만들지 않고 그것을 쓰는 쪽이 싸 보이지만, **그 신호는 다른 것을
// 뜻한다**: 레일은 웹소켓이고 결정은 **REST POST** 로 나간다. 레일이 재연결
// 중이어도 그 POST 는 멀쩡히 성공한다.
//
// 그 차이가 여기서 비싼 이유는 승인에 **기한**이 있기 때문이다. 웹소켓이 잠깐
// 끊겼다는 이유로 컨트롤을 감추면, 사람은 실제로 할 수 있는 결정을 못 하고
// 그 사이에 승인이 만료될 수 있다. 「모르면 막는다」가 옳은 자리와 「할 수
// 있는데 막는다」가 되는 자리는 다르다.
//
// NetInfo 는 「이 기기가 네트워크에 닿는가」를 말하고, 그것이 REST 가 나갈 수
// 있는가에 가장 가까운 신호다. 그리고 인박스가 이미 그것을 쓰므로, 같은 것을
// 쓰는 것이 두 화면의 결을 **같게 만드는 유일한 방법**이다.
// =============================================================================

/**
 * 낙관적 기본값 `true`.
 *
 * 첫 이벤트가 오기 전에 `false` 로 시작하면, 온라인인 사람이 화면을 열 때마다
 * 컨트롤이 한 순간 사라졌다 나타난다 — 그 깜빡임은 「지금 결정할 수 없다」는
 * 거짓 신호다. 실제로 끊겨 있으면 첫 이벤트가 곧 바로잡는다.
 */
export function useOnline(): boolean {
  const [online, setOnline] = useState(true);
  useEffect(() => {
    const unsubscribe = NetInfo.addEventListener(state => {
      setOnline(isOnlineFromNetInfo(state));
    });
    return unsubscribe;
  }, []);
  return online;
}

/**
 * 연결이 끊겼을 때 승인 컨트롤 자리에 서는 문장.
 *
 * 두 화면이 **같은 상수**를 든다. 복제하면 두 경로가 같은 상황에 다른 말을
 * 하기 시작하고, 그것이 이 파일이 존재하는 이유다.
 *
 * **이제 그 「두 화면」은 두 클라다** (U4-6, #1102). 문장은 여기서 landing 했고
 * 코어 `approvalNote.ts` 가 그대로 들고 갔다. 여기 남는 것은 **이름 하나**이고,
 * 값을 다시 적지 않는다 — 같은 값을 두 곳에 적는 순간 이 주석이 경고하는 그
 * 복제가 된다. 이름을 지우지 않는 이유는 이 파일이 인박스 화면의 진입점이고,
 * 「오프라인일 때 무슨 문장이 서는가」를 찾는 사람이 먼저 여는 자리가 여기이기
 * 때문이다.
 */
