// =============================================================================
// 앱이 말하는 문장
// =============================================================================
//
// 대화 안의 글자는 거의 전부 **누군가 친 것**이다. 그런데 몇 줄은 아니다 —
// 「삭제된 메시지」, 「내용 없는 메시지」, 「인용한 원본을 아직 불러오지
// 않았습니다」. 이것들은 메시지가 아니라 **메시지에 대한 서술**이고, 사람이 그
// 둘을 헷갈리면 앱의 해명을 남의 말로 읽는다.
//
// ## 왜 새 축이 필요했나 — italic 은 무동작이었다
//
// 첫 판은 그 구분을 `fontStyle:'italic'` + 한 급 흐린 회색으로 냈다. 그런데
// **한글 시스템 서체에는 italic 페이스가 없고 RN 에는 `fontSynthesis` 가
// 없다**(같은 사실이 `MessageBody.tsx` 머리말에도 적혀 있다). 즉 그 축은 우리가
// 실제로 출하하는 문자체계에서 **처음부터 아무 일도 하지 않았다** — 기울기 차
// 0 으로 픽셀 확증됐다.
//
// 남아 있던 실질 구분은 회색 한 단계뿐이었고, 그 한 단계의 크기는 **1.834:1**
// 이다(`textFaint` #6b7280 ↔ `textMuted` #9aa0a8). 게다가 `textFaint` 는 배경
// 대비 **3.909:1** 로 본문 AA(4.5)를 못 지난다. 즉 「눈에 잘 안 띄는 것」이
// 구분축을 겸하고 있었다.
//
// ## 색으로는 못 푼다
//
// 토큰 회색은 3단(`textFaint`/`textMuted`/`text`)이다. AA 를 지나면서 인용
// 본문(`textMuted`, 7.170:1)과 **다른** 회색이 남지 않는다. 본문 쪽을 `text` 로
// 올려 자리를 만드는 안은 「인용은 이 메시지의 맥락이지 내용이 아니다」라는
// 결정(design-review H-2)과 정면으로 충돌한다. 4번째 회색을 만드는 것은 토큰
// 체계 결정이라 여기서 할 일이 아니다.
//
// 그래서 축을 **글자 자체로** 옮긴다. 색은 AA 를 지나는 데만 쓰고, 구분은
// 서체·팔레트·플랫폼 어느 것에도 기대지 않는 것이 든다.
//
// ## 왜 `※` 인가
//
// 한국어 조판에서 `※` 는 문자 그대로 **주(註) 기호**다. 「여기부터는 본문이 아닌
// 알림」이라는 뜻을 범례 없이 전달한다 — 우리가 필요한 바로 그 뜻이다.
//
// 탈락시킨 후보들:
//
// - **`…`** — 이미 인용문 **잘림 접미사**다(`block.truncated`). 같은 글자가
//   「더 있다」와 「못 불러왔다」를 동시에 뜻하게 된다.
// - **`[삭제된 메시지]`(각괄호)** — 편집자 삽입 표시라 설명이 필요 없는 좋은
//   후보지만, 하필 **우리 규율이 이 모양을 위험하게 만든다**. 앱의 문장은 마크다운
//   파서를 타지 않으므로, 렌더되지 않은 `**` 를 본 적 있는 사람에게 `[...]` 는
//   「또 안 그려진 마크다운」으로 읽힌다.
// - **`⌀`(U+2300)** — SF Pro 수록이 불확실하다. 두부(□)가 뜨면 무동작보다 나쁜
//   **가시적 파손**이다. `※`(U+203B)는 한국어 iOS 폰트에 확실히 들어 있다.
//
// 그리고 이 선택은 대칭적으로 옳다: italic 이 죽은 이유가 「라틴 서체 관습에
// 기댔다」인데, 그 교정으로 **우리가 실제로 출하하는 문자체계에 토착인 표시**를
// 고른다.
//
// ## 기호는 하나다
//
// 묘비용·미해결용을 따로 두면 아무도 갖고 있지 않은 범례가 필요해진다. 이 축이
// 말할 것은 한 가지다 — **「이 줄은 저자가 아니라 앱이 말하는 문장이다」**. 어느
// 종류인지는 이미 낱말이 말한다.
//
// ## 보조기술에는 붙이지 않는다
//
// 로터가 읽을 라벨은 낱말만 든다. `※` 는 눈으로 훑을 때 「본문이 아님」을 즉시
// 주는 표시이지 소리 내어 읽을 것이 아니다 — 화면 낭독기는 순차적으로 듣기
// 때문에 「본문 사이에 섞여 있어서 못 알아본다」는 문제 자체가 없다. (같은 이유로
// 「작성 중」 줄의 말줄임표도 라벨에서 뺐다.)
// =============================================================================

