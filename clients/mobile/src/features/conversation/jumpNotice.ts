// =============================================================================
// 인용 점프가 빈손으로 돌아왔을 때의 고지
// =============================================================================
//
// 화면 안에 인라인으로 있던 문장을 밖으로 꺼냈다. 이유는 하나다 — **측정
// 하네스가 이 문장을 찍어야 하는데**(design-review H-5 는 「코드 확인 / 시각
// SKIPPED」로 남았다), 하네스가 `ConversationScreen` 을 통째로 마운트할 수는
// 없다(쿼리·실시간·세션이 전부 딸려 온다).
//
// 그런데 하네스가 문장을 **베껴 적으면** 그 사진은 증거가 아니다. 배송되는
// 문장이 바뀌어도 사진은 옛말을 계속 하고, 리뷰는 있지도 않은 화면을 본다.
// 그래서 두 곳이 **같은 상수**를 든다.
//
// ## 이것은 실패가 아니라 사실 진술이다 (H-5)
//
// 사람이 인용을 눌렀고, 원본은 **존재하며**, 아직 안 불러왔을 뿐이다. 그래서
// danger 가 아니라 `NoticeBlock` 이고, 첫 줄은 **무슨 일인지**, 둘째 줄은
// **무엇을 하면 되는지**다.
// =============================================================================

export interface JumpNotice {
  headline: string;
  detail: string;
}

/**
 * **무엇을** 찾다 못 찾았는가 (#1193 · #1196).
 *
 * 같은 기계를 **네 곳**이 탄다. 인용을 누른 사람에게 「인용한 원본」이라고 말하는
 * 것과 ADE 카드의 「대화로」를 누른 사람에게 같은 낱말로 말하는 것은 다른 일이다:
 * 뒤의 사람은 인용을 누른 적이 없고, 그 화면에서 그 문장은 **거짓**이다. 화면이
 * 「모르면 모른다고 말한다」를 지키는 자리에서 아는 것을 틀리게 말할 수는 없다.
 *
 * #1193 은 그 갈래를 **열기만 했다** — `quote` 와 `session` 둘뿐이었고, 고정 목록과
 * 검색 진입은 여전히 남의 낱말로 말했다(#1196):
 *
 *   - 고정(`pin`) — 고정 목록에서 원본으로 가는 점프가 「인용한 원본」이라고
 *     말했다. 그 사람은 인용이 아니라 **고정**을 눌렀다. #1193 이 `onJumpToPinned`
 *     의 주어를 `'quote'` 로 둔 채 갈래만 열어 둔 자리이고, 이 값이 그 소비다.
 *   - 검색(`search`) — 진입 앵커의 문장은 화면 안에 인라인으로 적혀 있었다. 그
 *     경로가 이제 같은 착지 기계를 타므로(#1196) 문장도 같은 곳에 산다. **낱말은
 *     한 글자도 안 바뀐다** — 옮겨 온 것이지 새로 쓴 것이 아니다.
 *
 * 조사가 낱말마다 갈린다: 「원본은 · 원본을」과 「메시지는 · 메시지를」. 그래서
 * 주어를 접두사로 갈아 끼울 수 없고, 문장을 통째로 든다.
 */
export type JumpSubject = 'quote' | 'pin' | 'search' | 'session';

/**
 * 「위쪽에 있다」고 **단정할 수 있는** 주어의 문장.
 *
 * `older` 는 원본의 `seq` 를 알 때만 온다(`Timeline` 이 로드된 가장 오래된 seq 와
 * 견주어 판정한다). 셋 다 그 값을 가질 수 있다 — 인용은 서버가 실어 주고, 고정
 * 목록 항목은 언제나 갖고 있으며, 검색 결과는 `messageId` 와 `seq` 를 함께 든다.
 */
const SUBJECT_NOUN: Readonly<Record<'quote' | 'pin' | 'search', [string, string]>> =
  {
    // [「…은/는 더 위쪽에 있습니다」의 주어, 「…을/를 찾지 못했습니다」의 주어]
    quote: ['인용한 원본은', '인용한 원본을'],
    pin: ['고정한 메시지는', '고정한 메시지를'],
    search: ['찾던 메시지는', '찾던 메시지를'],
  };

/**
 * 왜 못 갔는지에 따라 다른 문장을 든다.
 *
 * - `older` — 원본의 `seq` 를 안다. 그러면 「위쪽에 있다」고 **단정할 수 있다**.
 * - `unknown` — 라이브 프레임으로 온 인용에는 원본 `seq` 가 없다. 어디 있는지
 *   모르면 모른다고 말한다. 「위에 있습니다」는 그 경우 거짓일 수 있다.
 *
 * 세션 앵커(#1193)는 **언제나** `unknown` 이다: 세션 원장이 순서값을 나르지
 * 않으므로 없는 seq 를 지어내는 대신 아는 만큼만 말한다.
 */
export function jumpMissedNotice(
  reason: 'older' | 'unknown',
  subject: JumpSubject = 'quote',
): JumpNotice {
  const detail =
    reason === 'older'
      ? '아직 불러오지 않았습니다. 위로 올려 이어서 불러오세요.'
      : '위로 올려 이전 대화를 더 불러오세요.';
  if (subject === 'session') {
    // **`reason` 을 보지 않는다** (리뷰 N1). 세션 원장은 순서값을 나르지 않으므로
    // 이 주어로 오는 점프는 언제나 seq 를 모르고(`ConversationScreen` 이
    // `seq: null` 로 건다), 그래서 「더 위쪽에 있습니다」는 이 자리에서 말할
    // 자격이 없는 문장이다. 배송되지 않는 문구를 들고 있는 것은 다음 사람에게
    // 「이 갈래도 화면에 나온다」는 거짓 정보이고, 테스트가 그것을 지키면 그
    // 거짓말은 초록으로 보존된다.
    return {
      headline: '이 작업을 시작한 메시지를 이 화면에서 찾지 못했습니다',
      detail: '위로 올려 이전 대화를 더 불러오세요.',
    };
  }
  const [above, missing] = SUBJECT_NOUN[subject];
  return {
    headline:
      reason === 'older'
        ? `${above} 이 대화의 더 위쪽에 있습니다`
        : `${missing} 이 화면에서 찾지 못했습니다`,
    detail,
  };
}
