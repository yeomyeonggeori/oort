// =============================================================================
// 인용 점프가 빈손으로 돌아왔을 때의 고지
// =============================================================================
//
// 화면 안에 인라인으로 있던 문장을 밖으로 꺼냈다. 이유는 하나다 — **측정
// 하네스가 이 문장을 찍어야 하는데**(design-review H-5 는 「코드 확인 / 시각
// SKIPPED」로 남았다), 하네스가 `ConversationScreen` 을 통째로 마운트할 수는
// 없다(쿼리·실시간·세션이 전부 딸려 온다).
//
// 그런데 하네스가 문장을 **베껴 적으면** 그 사진은 증거가 아니다. 배송되는
// 문장이 바뀌어도 사진은 옛말을 계속 하고, 리뷰는 있지도 않은 화면을 본다.
// 그래서 두 곳이 **같은 상수**를 든다.
//
// ## 이것은 실패가 아니라 사실 진술이다 (H-5)
//
// 사람이 인용을 눌렀고, 원본은 **존재하며**, 아직 안 불러왔을 뿐이다. 그래서
// danger 가 아니라 `NoticeBlock` 이고, 첫 줄은 **무슨 일인지**, 둘째 줄은
// **무엇을 하면 되는지**다.
// =============================================================================

export interface JumpNotice {
  headline: string;
  detail: string;
}

/**
 * 왜 못 갔는지에 따라 다른 문장을 든다.
 *
 * - `older` — 원본의 `seq` 를 안다. 그러면 「위쪽에 있다」고 **단정할 수 있다**.
 * - `unknown` — 라이브 프레임으로 온 인용에는 원본 `seq` 가 없다. 어디 있는지
 *   모르면 모른다고 말한다. 「위에 있습니다」는 그 경우 거짓일 수 있다.
 */
export function jumpMissedNotice(reason: 'older' | 'unknown'): JumpNotice {
  return reason === 'older'
    ? {
        headline: '인용한 원본은 이 대화의 더 위쪽에 있습니다',
        detail: '아직 불러오지 않았습니다. 위로 올려 이어서 불러오세요.',
      }
    : {
        headline: '인용한 원본을 이 화면에서 찾지 못했습니다',
        detail: '위로 올려 이전 대화를 더 불러오세요.',
      };
}
