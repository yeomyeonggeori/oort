import * as Clipboard from 'expo-clipboard';

// =============================================================================
// 텍스트를 꺼내는 길 (goal U4-b / #1049, BL-2·H-9).
//
// ## 무엇이 없었나
//
// 폰에서 메시지 텍스트를 꺼낼 방법이 **하나도 없었다**. 선택은 꺼져 있었고
// (`selectable={!actionable}` — 액션이 하나라도 있는 행, 즉 사실상 모든 메시지),
// 액션 시트에 복사 항목도 없었다. 에이전트가 준 명령어·해시·경로를 **화면을 보고
// 손으로 옮겨 적어야** 했다.
//
// 그리고 그것은 실수가 아니라 **미해결 의존성**이었다. 옛 주석이 자인한다:
// *"A 복사 action needs a clipboard native module; RN's own is deprecated."*
// 이 파일이 그 의존성을 해결한다.
//
// ## 왜 이 파일이 세 줄이 아니라 여기 있나
//
// `expo-clipboard` 를 부르는 자리를 하나로 모은다. 부르는 곳이 둘 이상이 되면
// 「무엇을 복사하는가」의 답도 둘이 되고, 그 둘은 조용히 갈린다 — 이 배치가
// 인용·작성 중에서 계속 피해 온 그 모양이다.
// =============================================================================

/**
 * 클립보드에 넣는다. 성공 여부를 돌려준다.
 *
 * 던지지 않는다: 실패한 복사에 대해 화면이 할 말은 「안 됐다」뿐이고, 그 문장은
 * 부른 쪽이 자기 자리에서 말해야 한다(토스트가 아니라 제자리 — 이 클라이언트가
 * 반응·삭제 실패에서 이미 고른 규율).
 */
/**
 * 「복사됨」이 화면에 머무는 시간, ms.
 *
 * **두 복사가 이 값을 함께 쓴다** (design-review M-3). 코드 블록 버튼과 액션
 * 시트의 「복사하기」는 30pt 옆의 형제 컨트롤인데, 첫 판은 한쪽만 영수증을 냈다 —
 * 같은 동사가 두 가지 계약을 갖는 것으로 읽힌다. 통일하는 방향은 **말하는 쪽**
 * 이다: iOS 의 조용한 복사가 관례이긴 하나, 그 관례는 옆에서 다른 컨트롤이
 * 말하고 있지 않을 때의 것이다.
 */
export const COPY_RECEIPT_MS = 1_500;

export async function copyText(text: string): Promise<boolean> {
  try {
    await Clipboard.setStringAsync(text);
    return true;
  } catch {
    return false;
  }
}
