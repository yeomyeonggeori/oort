import {dismissAllNotificationsAsync} from 'expo-notifications';

// =============================================================================
// 로그아웃하는 폰의 알림 센터를 비운다 (#3931, 독립 보안 검수).
//
// 잠금 화면의 알림은 앱 밖의 일이다. 로그아웃은 토큰·캐시·초안을 지우지만 이미 와 있는 알림은
// 센터에 남고, 그중 승인 요청은 [승인]/[거절] 버튼을 단 채다. 자격을 지운 뒤라 누르면
// 「승인하지 못했어요」가 되지만(요청은 나가지 않는다), 앞 사람의 승인 요청과 메시지 미리보기가
// 로그아웃한 폰의 잠금 화면에 남아 있어서는 안 된다. 로그아웃은 「이 기기에서 내 흔적을 지운다」다.
//
// 못 비워도 로그아웃은 막히지 않는다: 알림 센터가 막지 못하는 로그아웃이어야 한다.
// =============================================================================

export async function dismissDeliveredNotifications(): Promise<void> {
  try {
    await dismissAllNotificationsAsync();
  } catch {
    // 못 비운 알림은 사람이 쓸어 낸다. 지금 하던 로그아웃은 계속된다.
  }
}
