/* eslint-env node, es2022 */
// Exact installed/locked FormatJS closure, plus the core's existing attribution.
// The phone also declares the core's runtime dependency (`@formatjs/intl`) itself, so the copy that
// ships comes from THIS lock (#4833 review). The core NOTICE below is its attribution; this tool
// checks that NOTICE covers exactly the locked versions instead of listing that closure twice.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const mobile = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(mobile, '../..');
const pkg = JSON.parse(readFileSync(resolve(mobile, 'package.json'), 'utf8'));
const lock = JSON.parse(readFileSync(resolve(mobile, 'package-lock.json'), 'utf8'));
const core = JSON.parse(readFileSync(resolve(root, 'packages/momo-core/package.json'), 'utf8'));
const coreNoticeText = readFileSync(resolve(root, 'packages/momo-core/NOTICE'), 'utf8');
const coreNoticeLines = coreNoticeText.split('\n');
const coreDependencies = core.dependencies ?? {};
const attributedByCore = new Set();
function attributeCore(name) {
  if (attributedByCore.has(name)) return;
  attributedByCore.add(name);
  const locked = lock.packages[`node_modules/${name}`];
  if (!locked) throw new Error(`Missing locked core dependency: ${name}`);
  if (!coreNoticeLines.some(line => line.startsWith(`${name}@${locked.version} — `))) {
    throw new Error(`packages/momo-core/NOTICE does not attribute the locked ${name}@${locked.version}`);
  }
  for (const dependency of Object.keys(locked.dependencies ?? {})) attributeCore(dependency);
}
for (const [name, version] of Object.entries(coreDependencies)) {
  if (pkg.dependencies[name] !== version) throw new Error(`The phone must declare core dependency ${name}@${version} exactly`);
  attributeCore(name);
}
const names = new Set();
function visit(name) {
  if (names.has(name)) return;
  if (!name.startsWith('@formatjs/')) throw new Error(`Unexpected polyfill dependency: ${name}`);
  names.add(name);
  const data = lock.packages[`node_modules/${name}`];
  if (!data) throw new Error(`Missing locked dependency: ${name}`);
  for (const dependency of Object.keys(data.dependencies ?? {})) visit(dependency);
}
for (const [name, version] of Object.entries(pkg.dependencies).filter(([dependency]) => dependency.startsWith('@formatjs/') && !(dependency in coreDependencies))) {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`Polyfill must be exactly pinned: ${name}`);
  visit(name);
}
const entries = [...names].sort().map(name => {
  const directory = resolve(mobile, 'node_modules', name);
  const installed = JSON.parse(readFileSync(resolve(directory, 'package.json'), 'utf8'));
  const locked = lock.packages[`node_modules/${name}`];
  if (installed.version !== locked.version || installed.license !== 'MIT') throw new Error(`Unexpected package/version/license: ${name}`);
  const license = readFileSync(resolve(directory, 'LICENSE.md'), 'utf8').trim();
  return `========================================================================\n${name}@${installed.version} — ${installed.license}\nSource: https://github.com/formatjs/formatjs\nUnmodified upstream LICENSE.md:\n========================================================================\n\n${license}\n`;
});
const output = `oort mobile Intl attribution — ADR-0213 / #4833\n\nGenerated by clients/mobile/scripts/generate-intl-notices.mjs.\nThis file and the core NOTICE must accompany phone redistribution.\nThis is the Intl addition, not a complete React Native/CocoaPods inventory.\nOnly ko/en per-language plural/relative-time data is imported by the app.\n\n${coreNoticeText}\n${entries.join('\n')}`;
const path = resolve(root, 'legal/generated/MOBILE_INTL_NOTICES.txt');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('Stale mobile Intl notice bundle.');
} else writeFileSync(path, output);
console.log(`Mobile Intl notices: ${names.size} polyfill packages + core (${attributedByCore.size} locked core packages attributed), PASS`);
