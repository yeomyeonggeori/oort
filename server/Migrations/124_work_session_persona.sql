-- 124_work_session_persona.sql — #3592 P1 (ADR-0198 증보 1 D7 · 「T5 확정」 6)
--
-- 개인 에이전트(별칭 멤버)를 부른 세션은 카드·진행·답의 표시 작성자가 그 별칭 멤버다.
-- 세션 소유자(`work_session.member_id`)는 계속 사람 소유자다 — 슬롯·지시·허락·종료가
-- 모두 그 열로 소유권을 판단하므로 바꾸지 않는다. 바뀌는 것은 "누구 이름으로 메시지가
-- 남는가"뿐이라 열을 하나 더한다.
--
--   work_session.persona_member_id
--       서버가 서명된 spawn 컨트롤의 `human_spawn_agent_member_id`에서 도출해 세션을 만들 때
--       한 번 적는다(host는 이 값을 보내지도 고르지도 않는다 — 별칭 사칭 불가). NULL이면
--       「내 도구」 직접 세션이거나 개인 에이전트 표지가 없는 에이전트라 종전처럼 소유자 이름으로
--       남는다. 재개한 후속 세션은 원본의 값을 이어받는다.
--
-- 별칭 멤버가 그 채널의 멤버일 필요는 없다(결재 2026-10-08 「소유자면 어디서나」): 메시지의
-- author는 멤버십을 요구하지 않고, 읽기는 채널 멤버십으로 걸린다.
--
-- RLS: `work_session`은 019의 테넌트 테이블이고 FORCE RLS + ws_isolation 대상이다. 열 추가는 그
-- 정책을 그대로 물려받는다. 새 테이블·새 권한 없음. schema_v0.sql 무접촉.
-- =============================================================================

ALTER TABLE work_session
  ADD COLUMN persona_member_id uuid REFERENCES member(id);

COMMENT ON COLUMN work_session.persona_member_id IS
  '#3592 ADR-0198 증보 1 D7: 이 세션을 부른 개인 에이전트(별칭 멤버). 카드·진행·답의 표시 작성자. 서버가 서명된 spawn 컨트롤에서 도출하며 host 입력이 아니다. NULL = 소유자 이름으로 남는다.';
